#: how much slower than the SAME cell of the baseline arm a body may run before
#: it is called slow. A second budget alone cannot be the only reading: it names
#: an absolute cost, so an injected burn below it - the 0.05 s of the bench suite
#: against the 30 s default - passes while having doubled the task's own runtime.
#: The relative reading is what a CI regression report needs anyway, because the
#: regression a pull request introduces is relative to what the task cost before.
SLOW_BODY_RATIO = 2.0

#: and by how much, in seconds, so that a 2x of a sub-millisecond body - which is
#: the noise floor of a container - is not reported as a defect
SLOW_BODY_MIN_DELTA = 0.01

#: the scale ladder the epic names for query growth (1/10/100+ records). A
#: detection needs at least two rungs; the third makes the slope trustworthy.
SCALE_LADDER = (1, 10, 100)

#: how far above the reviewed calls-per-unit a unit may sit before a call is
#: called a duplicate; a fraction of one call is a rounding of the same call
DUPLICATE_CALL_TOLERANCE = 0.5

#: a duplicated call asks for the answer twice, so the signature against the
#: workload's own baseline arm is a DOUBLING - not merely more calls, which a
#: retry also produces. Counts are integers, hence the epsilon rather than a
#: percentage band: a band wide enough to forgive a retry would also forgive the
#: 1-becomes-2 duplicate which the real harvesting fan-out produced.
DUPLICATE_FACTOR = 2.0

#: a legitimately linear task costs a fixed amount per unit, so the excess a
#: measured slope may show over the expectation before it is called a defect
PER_UNIT_TOLERANCE = 0.5

#: a slope which more than doubles between the bottom and the top of the size
#: ladder is super-linear: quadratic growth doubles itself over a decade, and a
#: task with a fixed cost and a linear cost does not. This is the one N+1
#: verdict that needs no expectation from the caller.
SUPERLINEAR_FACTOR = 2.0


def workload_size(record):
    """How big this workload was, which is what a per-unit figure divides by.

    ``records`` is the size of the thing the task was pointed at - catalogue
    records, backlog rows, probes - and it is the size the measured totals grow
    with. It is NOT the number of timed samples: one fire of a 1000-row chunk
    produces one timing and a thousand statements, and a ladder built on the
    samples of a run would ask "how often was it measured" instead of "how does
    the cost grow with the work".
    """
    for candidate in (record.get("records"),
                      (record.get("workload") or {}).get("units")):
        if isinstance(candidate, int) and candidate > 0:
            return candidate
    return None


def total_of(record, key):
    """The measured total of one counter of one record, or None.

    The totals, not their per-unit form, are what a slope is fitted on: per-unit
    figures divide the fixed cost of a run by its size, so the same code reads
    as a thousand statements per record at one size and one at another.
    """
    block = record.get(key) if isinstance(record.get(key), dict) else None
    if block is None:
        for group in ("sql", "http", "pressure"):
            candidate = (record.get(group) or {}).get(key)
            if isinstance(candidate, dict):
                block = candidate
                break
    if not isinstance(block, dict):
        return None
    value = block.get("value", block.get("total_ms"))
    if value is None:
        return None
    size = workload_size(record)
    if not size:
        return None
    return {"total": float(value), "size": size,
            "evidence": block.get("evidence", "measured")}


def scale_ladder_of(records):
    """The records of one arm/family ordered by their workload size."""
    sized = []
    for record in records:
        size = workload_size(record)
        if size is not None:
            sized.append((size, record))
    sized.sort(key=lambda pair: pair[0])
    return sized


def _ladder_totals(ladder, key):
    """``[(size, {"total": peak, "mean": .., "n": ..})]`` over distinct sizes.

    Repeats share a size, and a slope needs distinct sizes: pooling seven repeats
    of one workload and reading them as two rungs would answer "how fast" with
    "how often it was run".

    The verdict reads the LARGEST repeat of a rung, not its mean. A statement
    count is a property of the workload, so the repeat which actually processed
    the backlog is the one that shows its shape - and a run where five of seven
    repeats found an empty table is a data-quality problem the record already
    labels through its outcome distribution, not evidence that the work is
    cheap. Averaging those two readings together would hide the per-row cost
    behind the repeats that did no work, which is a false green.
    """
    by_size = {}
    for size, record in ladder:
        block = total_of(record, key)
        if block is None:
            continue
        by_size.setdefault(size, []).append(block)
    rungs = []
    for size, blocks in sorted(by_size.items()):
        totals = [block["total"] for block in blocks]
        peak = max(blocks, key=lambda block: block["total"])
        rungs.append((size, {"total": peak["total"],
                             "mean": sum(totals) / len(totals),
                             "n": len(totals),
                             "evidence": peak.get("evidence", "measured")}))
    return rungs


def _slope_of(rungs):
    """(total_top - total_bottom) / (size_top - size_bottom), or None."""
    if len(rungs) < 2:
        return None
    (size_low, low), (size_high, high) = rungs[0], rungs[-1]
    if size_high == size_low:
        return None
    return (high["total"] - low["total"]) / (size_high - size_low)


def _peak_total(records, key):
    """Largest measured total of one counter over the arm's biggest rung."""
    rungs = _ladder_totals(scale_ladder_of(records), key)
    return rungs[-1] if rungs else (None, None)


def detect_regression(records, budget_seconds=None, expected_http_per_unit=None,
                      expected_statements_per_unit=None, baseline=None):
    """The three detections of the acceptance list, over one arm's records.

    Returns a list of finding dicts, each naming the kind, the evidence and the
    numbers it was computed from - a finding without its numbers is not a
    finding. Nothing here guesses a sample: a detector which lacks its input
    reports ``insufficient_data`` instead of a verdict.
    """
    findings = []
    if not records:
        return [{"kind": "insufficient_data", "reason": "no records"}]
    ladder = scale_ladder_of(records)
    for metric, key, expectation in (
            ("sql_statements", "statements", expected_statements_per_unit),
            ("sql_time_ms", "total_ms", None),
            ("http_calls", "calls", expected_http_per_unit)):
        rungs = _ladder_totals(ladder, key)
        if len(rungs) < 2:
            continue
        sizes = [size for size, _values in rungs]
        _min_size, smallest = rungs[0]
        _max_size, largest = rungs[-1]
        # the growth of the TOTAL, over the size of the workload: a task which
        # legitimately reads one row per record pays a linear amount, and a
        # slope alone cannot tell that from a defect. What a slope CAN decide
        # without any expectation is super-linearity - growth that accelerates
        # as the ladder climbs - so that is the verdict which needs no input,
        # and anything quieter than that is judged against what a unit
        # legitimately costs, which only the caller knows.
        slope = _slope_of(rungs)
        head = _slope_of(rungs[:2])
        tail = _slope_of(rungs[-2:])
        superlinear = (len(rungs) >= 3 and head is not None and tail is not None
                       and tail > max(head * SUPERLINEAR_FACTOR, 1e-9))
        finding = {
            "kind": "sql_n_plus_one" if metric != "http_calls"
            else "duplicate_remote_call",
            "metric": metric,
            "sizes": sizes,
            "total_at_min": round(smallest["total"], 6),
            "total_at_max": round(largest["total"], 6),
            "per_unit_at_min": round(smallest["total"] / _min_size, 6),
            "per_unit_at_max": round(largest["total"] / _max_size, 6),
            "slope": None if slope is None else round(slope, 6),
            "head_slope": None if head is None else round(head, 6),
            "tail_slope": None if tail is None else round(tail, 6),
            "superlinear": superlinear,
            "expected_per_unit": expectation,
            "excess_per_unit": (round(slope - expectation, 6)
                                if expectation is not None and slope is not None
                                else None),
            "repeats_at_max": largest["n"],
            "evidence": largest.get("evidence", "measured"),
        }
        if expectation is not None:
            tolerance = (DUPLICATE_CALL_TOLERANCE if metric == "http_calls"
                         else PER_UNIT_TOLERANCE)
            finding["detected"] = bool(
                slope is not None and slope > expectation + tolerance)
        else:
            # no expectation: only the shape the caller cannot have asked for
            # speaks - growth which accelerates down the ladder
            finding["detected"] = bool(superlinear)
            finding["note"] = (
                "needs --expected-http-per-unit: a call duplicated at every "
                "size is linear, and a slope cannot see a linear duplicate"
                if metric == "http_calls" else
                "linear growth cannot be judged without "
                "--expected-statements-per-unit; super-linear growth is a "
                "verdict on its own")
        if metric == "http_calls" and baseline:
            # a call duplicated at EVERY size is linear, so no slope and no
            # expectation of a per-unit count sees it - what the real run of
            # harvesting.fan_out showed. The reading which does is the same
            # workload's own baseline arm: a unit making one remote call which
            # is measured making two is the duplicate, whatever its growth.
            base_size, base = _peak_total(baseline, key)
            if base is not None and base_size == _max_size:
                finding["baseline_total_at_max"] = base["total"]
                finding["detected"] = bool(
                    largest["total"] > DUPLICATE_CALL_TOLERANCE
                    and largest["total"] + 1e-9
                    >= base["total"] * DUPLICATE_FACTOR)
                finding["evidence"] = "measured"
                finding["note"] = (
                    "judged against the baseline arm of the same workload: a "
                    "duplicate which duplicates at every size is linear")
        findings.append(finding)
    # slow task body and queue wait are judged PER SCALE CELL, never over the
    # whole arm: a second budget names what one fire of ONE workload may take,
    # and the 1000-record rung of a family legitimately costs more than its
    # 1-record rung. Pooling the two would apply the budget of one cell to the
    # other and report the difference as a defect.
    cells = {}
    for record in records:
        cells.setdefault((record.get("scale"), record.get("records")),
                         []).append(record)
    base_cells = {}
    for record in (baseline or []):
        base_cells.setdefault((record.get("scale"), record.get("records")),
                              []).append(record)
    for (_scale, _size), rows in sorted(cells.items(),
                                        key=lambda item: str(item[0])):
        pooled = []
        for record in rows:
            values, _derived = sample_values(record, "active")
            pooled.extend(values)
        if pooled:
            p95 = percentile(pooled, 0.95)
            budget = (budget_seconds if budget_seconds is not None
                      else DEFAULT_SLOW_BODY_SECONDS)
            # the same cell of the clean arm, when the run carries one: an
            # absolute budget is a ceiling a human set, and an injected burn
            # below it is still twice what the task used to cost
            base_pooled = []
            for record in base_cells.get((_scale, _size), []):
                values, _derived = sample_values(record, "active")
                base_pooled.extend(values)
            base_p50 = percentile(base_pooled, 0.50) if base_pooled else None
            p50 = percentile(pooled, 0.50)
            over_budget = bool(p95 is not None and p95 > budget)
            over_baseline = bool(
                p50 is not None and base_p50 is not None
                and p50 >= base_p50 * SLOW_BODY_RATIO
                and p50 - base_p50 >= SLOW_BODY_MIN_DELTA)
            finding = {
                "kind": "slow_task_body",
                "scale": _scale,
                "records": _size,
                "p95_seconds": p95,
                "n": len(pooled),
                "budget_seconds": budget,
                "detected": bool(over_budget or over_baseline),
                # a p95 is only a p95 from a real sample; below the floor the
                # verdict is the median and the record says so
                "percentile": ("p95" if len(pooled) >= P95_MIN_SAMPLES
                               else "p50"),
                "evidence": "measured",
            }
            if base_p50 is not None:
                finding["baseline_p50_seconds"] = base_p50
                finding["baseline_n"] = len(base_pooled)
                finding["ratio_to_baseline"] = (
                    round(p50 / base_p50, 3) if base_p50 else None)
                finding["ratio_floor_seconds"] = SLOW_BODY_MIN_DELTA
            findings.append(finding)
        # queue wait inflation, reported apart from the body: the #1330 rule
        waits = []
        for record in rows:
            values, _derived = sample_values(record, "queue")
            waits.extend(values)
        if waits:
            active_p50 = percentile(pooled, 0.50) if pooled else None
            wait_p50 = percentile(waits, 0.50)
            findings.append({
                "kind": "queue_wait_inflation",
                "scale": _scale,
                "records": _size,
                "queue_p50_seconds": wait_p50,
                "active_p50_seconds": active_p50,
                "n": len(waits),
                "detected": bool(wait_p50 is not None
                                 and active_p50 is not None
                                 and wait_p50 > max(1.0, 10 * active_p50)),
                "note": "reported apart: a message which waited is not a slow"
                        " task",
                "evidence": "measured",
            })
    return findings


DEFAULT_SLOW_BODY_SECONDS = 30.0


def cmd_detect(args):
    """Print the findings for one arm, and exit non-zero when asked to fail on them.

    This is the executable half of the acceptance bullet "demonstrates detection
    of an injected SQL N+1, duplicate remote call or slow task body against a
    statistically stable baseline": the same detector runs on the synthetic
    fixtures of the offline suite and on the real task bodies of the Django bench.
    """
    records = filter_records(load_records(args.infile), args.family, args.arm)
    if not records:
        raise SystemExit("no records for arm %r family %r"
                         % (args.arm, args.family))
    # one ladder per (family, seed): a run without --family holds several
    # families, and a slope fitted across two of them would ask how the cost of
    # one task grows with the size of another - and read the peak of the biggest
    # family as the shape of all of them
    groups = {}
    for record in records:
        groups.setdefault((record["family"], record.get("seed")), []).append(record)
    all_records = load_records(args.infile)
    findings = []
    for (family, seed), rows in sorted(groups.items(), key=lambda item: str(item[0])):
        # a per-unit expectation belongs to the family, so it is resolved per
        # group and never carried from the first family of the file to the rest
        contract = contract_of(family)
        statements = (args.expected_statements_per_unit
                      if args.expected_statements_per_unit is not None
                      else contract.get("statements_per_unit"))
        calls = (args.expected_http_per_unit
                 if args.expected_http_per_unit is not None
                 else contract.get("http_calls_per_unit"))
        baseline = None
        if args.baseline_arm:
            # absent is not an error: a single-arm file is a legitimate thing to
            # point at, and a linear duplicate call judged against nothing simply
            # goes unjudged - which the note below says out loud
            baseline = [record for record
                        in filter_records(all_records, family, args.baseline_arm)
                        if record.get("seed") == seed] or None
        for finding in detect_regression(
                rows, budget_seconds=args.slow_body_seconds,
                expected_http_per_unit=calls,
                expected_statements_per_unit=statements,
                baseline=baseline):
            finding["family"] = family
            finding["seed"] = seed
            findings.append(finding)
    # an arm spans the scale cells of its ladder, so it has one digest per rung;
    # reporting only the first would let a reader believe a finding about the
    # 1000-record cell described the 1-record cell too
    digests = sorted({record.get("digest") for record in records})
    families = sorted({record["family"] for record in records})
    report = {
        "schema": SCHEMA_VERSION,
        "kind": "detect",
        "arm": args.arm,
        "family": families[0] if len(families) == 1 else None,
        "families": families,
        "workload_digest": digests[0] if len(digests) == 1 else None,
        "workload_digests": digests,
        "baseline_arm": args.baseline_arm if args.baseline_arm else None,
        "ts": parse_now(args.now),
        "findings": findings,
        "detected": sorted({finding["kind"] for finding in findings
                            if finding.get("detected")}),
    }
    print(json.dumps(report, indent=2, sort_keys=True))
    if args.out:
        with open(args.out, "w", encoding="utf-8") as handle:
            handle.write(canonical(report) + "\n")
    print("arm=%s findings=%d detected=%s" % (
        args.arm, len(findings),
        ",".join(report["detected"]) or "none"), file=sys.stderr)
    if args.fail_on and report["detected"]:
        return 1
    return 0


