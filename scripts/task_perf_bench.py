# --------------------------------------------------------------------- helpers


def now_iso():
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def parse_now(value):
    """--now accepts an ISO stamp so a run of the suite is reproducible."""
    if not value:
        return now_iso()
    try:
        parsed = datetime.fromisoformat(value)
    except ValueError as exc:
        raise SystemExit("--now is not an ISO 8601 timestamp: %s" % exc)
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    return parsed.astimezone(timezone.utc).isoformat(timespec="seconds")


def canonical(value):
    """The canonical JSON of a value: keys sorted, so equal workloads hash equal."""
    return json.dumps(value, sort_keys=True, separators=(",", ":"),
                      default=str)


def workload_digest(record):
    """sha256 over the workload-identity keys of one record.

    Two arms of the same workload hash the same whatever their timings say; two
    arms of different workloads must never be compared, and `compare` enforces it.
    """
    identity = {key: record.get(key) for key in WORKLOAD_KEYS
                if record.get(key) is not None}
    return hashlib.sha256(canonical(identity).encode("utf-8")).hexdigest()[:16]


def percentile(values, q):
    """Nearest-rank percentile, the same definition as http_process_bench.

    The sample sizes of these reports are tens, not thousands; the simpler
    definition is honest here and the offline suite pins it.
    """
    if not values:
        return None
    ordered = sorted(values)
    rank = int(-(-q * len(ordered) // 1))
    return ordered[min(rank - 1, len(ordered) - 1)]


def mean(values):
    if not values:
        return None
    return sum(values) / len(values)


def coefficient_of_variation(values):
    """The repeatability number of an arm: stdev / mean over the repeat medians.

    A single number a human can set a threshold against; `None` when there is not
    enough data to state it at all, which is different from 0.0.
    """
    if len(values) < 2:
        return None
    average = mean(values)
    if not average:
        return None
    variance = sum((value - average) ** 2 for value in values) / (len(values) - 1)
    return (variance ** 0.5) / average


#: the sampling floor for p99 - below it the percentile is not reported at all,
#: which is the acceptance criterion "p50/p95/p99 when adequately sampled"
P99_MIN_SAMPLES = 100
P95_MIN_SAMPLES = 20


def duration_stats(values, label):
    """The honest duration block of one sample list.

    ``p95`` answers None below ``P95_MIN_SAMPLES``, ``p99`` below
    ``P99_MIN_SAMPLES``: a thin sample is labelled, never dressed up. ``n`` and
    ``evidence`` travel with every number.
    """
    values = [float(v) for v in values if v is not None]
    if not values:
        return {"label": label, "n": 0, "evidence": "measured",
                "min": None, "mean": None, "p50": None, "p95": None,
                "p99": None, "max": None, "reported": []}
    block = {
        "label": label,
        "n": len(values),
        "evidence": "measured",
        "min": round(min(values), 6),
        "mean": round(mean(values), 6),
        "p50": round(percentile(values, 0.50), 6),
        "max": round(max(values), 6),
        "p95": round(percentile(values, 0.95), 6)
        if len(values) >= P95_MIN_SAMPLES else None,
        "p99": round(percentile(values, 0.99), 6)
        if len(values) >= P99_MIN_SAMPLES else None,
    }
    block["reported"] = [key for key in
                         ("p50", "p95", "p99", "mean", "min", "max")
                         if block[key] is not None]
    return block


def resolve_repeats(spec):
    """Parse ``--repeats``: a positive integer, or ``auto``.

    ``auto`` is what the CI report path uses: repeat until the arm's own
    coefficient of variation is inside ``--cv-target`` (3 % by default) or the
    cap is reached, which is how a stable arm pays for seven runs and a noisy
    one does not silently publish a verdict built on two.
    """
    if isinstance(spec, int):
        return max(1, spec), None
    text = str(spec).strip().lower()
    if text == "auto":
        return 0, "auto"
    try:
        return max(1, int(text)), None
    except ValueError:
        raise SystemExit("--repeats wants a positive integer or 'auto', got %r"
                         % spec)


def load_records(path, kind=None):
    """The records of a JSONL file; a malformed line is a hard error, not a skip.

    A silently dropped line in a performance report is exactly how a flaky gate
    is born, so the reader refuses the file instead of averaging what is left.
    """
    records = []
    with open(path, encoding="utf-8") as handle:
        for number, line in enumerate(handle, 1):
            line = line.strip()
            if not line:
                continue
            try:
                record = json.loads(line)
            except ValueError as exc:
                raise SystemExit("%s:%d: not JSON (%s)" % (path, number, exc))
            if not isinstance(record, dict):
                raise SystemExit("%s:%d: not an object" % (path, number))
            if kind is None or record.get("kind", "load") == kind:
                records.append(record)
    if not records:
        raise SystemExit("%s holds no %s record" % (path, kind or "record"))
    return records


def append_record(path, record):
    """Append one record as a canonical JSON line, or print it when told to.

    Without `--out` the record goes to stdout as ONE line (so `load | record`
    and `load | jq` work) and the human summary goes to stderr - a log line
    must never be able to corrupt the artifact stream.
    """
    if not path:
        print(canonical(record))
        return
    directory = os.path.dirname(os.path.abspath(path))
    if directory and not os.path.isdir(directory):
        raise SystemExit("--out directory %s does not exist" % directory)
    with open(path, "a", encoding="utf-8") as handle:
        handle.write(canonical(record) + "\n")


def filter_records(records, family=None, arm=None, scale=None, kind="load"):
    selected = [r for r in records if r.get("kind", "load") == kind]
    if family:
        selected = [r for r in selected if r.get("family") == family]
    if arm:
        selected = [r for r in selected if r.get("arm") == arm]
    if scale:
        selected = [r for r in selected if r.get("scale") == scale]
    return selected


