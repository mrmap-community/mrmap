REQUIRED_FIELDS = ("schema", "kind", "family", "arm", "seed", "ts",
                   "repeats_planned", "durations", "quality")

#: a record which names no code revision cannot be re-run against the same code
REQUIRED_PRESENCE = ("revision", "environment")


def validate_record(record, source="record"):
    """Structural honesty checks, run on every read and on every write.

    These are the acceptance criteria turned into code: the three durations stay
    distinct, no invented sample, no unlabelled evidence, no comparison across
    different workloads (`compare` checks the digest, this checks that a digest
    can be checked at all).
    """
    where = "%s record" % source
    missing = [key for key in REQUIRED_FIELDS if key not in record]
    if missing:
        raise SystemExit("%s is missing %s" % (where, ", ".join(missing)))
    if record["schema"] != SCHEMA_VERSION:
        raise SystemExit("%s has schema %r, this tool speaks %r"
                         % (where, record["schema"], SCHEMA_VERSION))
    if record["kind"] not in ("load", "heavy"):
        raise SystemExit("%s has unknown kind %r" % (where, record["kind"]))
    family = record.get("family")
    if family not in FAMILIES:
        raise SystemExit(
            "%s names family %r; the first-party families are %s"
            % (where, family, ", ".join(sorted(FAMILIES))))
    if not str(record.get("arm", "")).strip():
        raise SystemExit("%s has no arm label" % where)
    if not isinstance(record.get("seed"), int):
        raise SystemExit("%s has no integer --seed; an unseeded workload is not "
                         "reproducible" % where)
    planned = record.get("repeats_planned")
    if not isinstance(planned, int) or planned < 1:
        raise SystemExit("%s does not name how many repeats were planned" % where)
    for key in REQUIRED_PRESENCE:
        if key not in record:
            raise SystemExit("%s does not document %s" % (where, key))
    if record.get("revision") in ("", None):
        # None is an honest answer (an exported tree has no git), an empty string is not
        if record.get("revision") == "":
            raise SystemExit("%s has an empty revision; use null when git cannot "
                             "answer" % where)
    durations = record["durations"]
    if not isinstance(durations, dict):
        raise SystemExit("%s: durations must be an object" % where)
    for key in ("active", "queue", "end_to_end"):
        block = durations.get(key)
        if block is None:
            continue
        if not isinstance(block, dict):
            raise SystemExit("%s: durations.%s must be an object" % (where, key))
        if block.get("n", 0) and block.get("evidence") is None:
            raise SystemExit("%s: durations.%s carries samples without an "
                             "evidence label" % (where, key))
        if block.get("evidence") and block["evidence"] not in EVIDENCE_LABELS:
            raise SystemExit("%s: durations.%s evidence %r is not one of %s"
                             % (where, key, block["evidence"],
                                ", ".join(sorted(EVIDENCE_LABELS))))
    active = durations.get("active") or {}
    queue = durations.get("queue") or {}
    if active.get("evidence") == queue.get("evidence") == "derived" \
            and active.get("n") and queue.get("n") \
            and active.get("p50") == queue.get("p50") \
            and active.get("n") == queue.get("n"):
        # the #1330 conflation mistake, caught structurally rather than in review
        raise SystemExit("%s: active and queue carry the same derived sample - "
                         "worker occupancy and broker wait are two different "
                         "measurements" % where)
    for key, block in durations.items():
        if not isinstance(block, dict):
            continue
        n = block.get("n", 0)
        for percentile_key, floor in (("p99", P99_MIN_SAMPLES),
                                      ("p95", P95_MIN_SAMPLES)):
            if block.get(percentile_key) is not None and n < floor:
                raise SystemExit(
                    "%s: durations.%s reports %s from %d sample(s); the floor "
                    "is %d. Report it as p50/max or measure more"
                    % (where, key, percentile_key, n, floor))
    evidence = record.get("evidence")
    if evidence is not None and evidence not in EVIDENCE_LABELS:
        raise SystemExit("%s: evidence %r is not one of %s"
                         % (where, evidence, ", ".join(sorted(EVIDENCE_LABELS))))
    quality = record["quality"]
    if not isinstance(quality, dict):
        raise SystemExit("%s: quality must be an object" % where)
    if quality.get("retention_truncated") and not quality.get("retention_note"):
        raise SystemExit("%s: a retention-truncated window needs a note saying "
                         "what was truncated" % where)
    pressure = record.get("pressure", {})
    if not isinstance(pressure, dict):
        raise SystemExit("%s: pressure must be an object" % where)
    return record


