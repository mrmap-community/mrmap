"""The raw XML source view writes back as an ordinary json:api attribute (#1247).

The metadata editor's source screen (design document §5, mockup
`proposed-04-xml-source.png`) sends the curator's edited document as a PATCH
of the record's `xml_backup_file` attribute — the json:api CRUD default
decided in the review of the design document, no bespoke action endpoint.
The reads of that attribute are untouched: they answer the url of the stored
media file, exactly as the autogenerated FileField did, so the download of
the same bytes and every other consumer keep working. What is new is the
WRITABLE representation: the document text. Pinned top-down:

* a raw write makes the SUBMITTED document the served one — what the rules
  were run over is what gets served, header included;
* the values the form maps flow the other way, out of the document into the
  row (title, keywords, contacts, ...); a field the document leaves out
  keeps the row's value — the next FORM save regenerates the mapped
  elements from the database, and that is the value which survives here;
* the header stays the row's: the submitted document's fileIdentifier must
  name THIS record and its dateStamp is replaced by the stamp this very
  editor save bumped (#1241 AC 2 — a raw write flags and bumps like any
  edit); last-write-wins, no token (§7 decision 6);
* an invalid document is refused like any failing on-save validation (#1243)
  BEFORE anything commits: not well-formed, naming another record, missing
  a dateStamp, violating a profile rule, POSTed, or sent alongside other
  members — each one a json:api 400 naming the member, nothing changed; a
  PUT is not even routed (the detail view answers PATCH, not PUT, #1244);
* permission and gate behave as on every other write (#1241): canEdit or
  403, closed gate or 403.
"""

from pathlib import Path

from django.contrib.auth import get_user_model
from django.core.files.base import ContentFile
from django.test import TestCase, override_settings
from django.utils import timezone
from guardian.shortcuts import assign_perm
from lxml import etree
from registry.mappers.factory import MDMetadataXmlMapper
from registry.models.metadata import (DatasetMetadataRecord, Keyword,
                                      MetadataContact)
from rest_framework.test import APIClient
from tests.django.registry.tests_metadata_profile import ensure_generic_profile
from tests.django.registry.tests_record_validation_on_save import (
    api, api_body, document_without, file_identifier_of)

ISO_DATA = Path(__file__).resolve().parents[1] / "test_data" / "iso_metadata"

#: the wire member of the source attribute (JSON_API_FORMAT_FIELD_NAMES
#: is "camelize"; the serializer raises with the snake model field name)
WIRE = "xmlBackupFile"

_CONTACT_KEY_FIELDS = tuple(
    next(c for c in MetadataContact._meta.constraints
         if getattr(c, "fields", None)
         and "name" in c.fields).fields)


def served_values(record):
    """The mapped values of the record's stored document (its CSW answer)."""
    document = record.xml_backup
    return MDMetadataXmlMapper.extract_mapped_values(document)[0]["values"]


def with_element_text(xml: bytes, path: str, text: str) -> bytes:
    """The document with the first node matching `path` carrying `text`.

    Mirrors what the source screen's editor does: the curator edits one text
    node of the document; everything else stays byte what it was.
    """
    root = etree.fromstring(xml)
    node = root.xpath(path)[0]
    node.text = text
    return etree.tostring(root, xml_declaration=True, encoding="utf-8")


def title_path():
    return ("//*[local-name()='identificationInfo']"
            "//*[local-name()='title']/*[local-name()='CharacterString']")


class SourceApiMixin:
    """Curator + generic-profile dataset record carrying the corpus document."""

    fixtures = ["test_users.json"]

    @classmethod
    def setUpTestData(cls):
        super().setUpTestData()
        get_user_model().objects.get_or_create(username="AnonymousUser")
        cls.contact = MetadataContact.objects.create(name="Source contact")
        cls.profile = ensure_generic_profile()
        cls.doc = document_without()
        cls.fid = file_identifier_of(cls.doc)
        cls.curator = get_user_model().objects.create_user(
            "source-curator", password="test")
        cls.stranger = get_user_model().objects.create_user(
            "source-stranger", password="test")

    def record(self, title="Record before the raw write",
               with_document=True):
        record = DatasetMetadataRecord.objects.create(
            title=title, file_identifier=self.fid, profile=self.profile,
            metadata_contact=self.contact, dataset_contact=self.contact)
        if with_document:
            record.xml_backup_file.save(
                "record.xml", ContentFile(self.doc), save=False)
            record.save(mark_customized=False)
        assign_perm("registry.change_datasetmetadatarecord", self.curator)
        assign_perm("registry.change_datasetmetadatarecord", self.curator,
                    record)
        return record

    def api_client(self, user=None):
        client = APIClient()
        client.force_authenticate(user=user or self.curator)
        return client

    def patch_source(self, record, text, attributes=None, relationships=None):
        """The PATCH the source screen sends: the document stands alone."""
        return api(self.api_client(), "patch",
                   f"/api/registry/dataset-metadata/{record.pk}",
                   api_body(pk=record.pk,
                            attributes={WIRE: text, **(attributes or {})},
                            relationships=relationships))

    def document_bytes(self, record):
        with open(record.xml_backup_file.path, "rb") as handle:
            return handle.read()


class SourceAttributeAnswerTests(SourceApiMixin, TestCase):
    """The reads of ``xml_backup_file`` answer today's file url, unchanged."""

    def test_the_detail_answer_carries_the_document_url(self):
        record = self.record()
        status, answer = api(
            self.api_client(), "get",
            f"/api/registry/dataset-metadata/{record.pk}")
        self.assertEqual(status, 200, answer)
        url = answer["data"]["attributes"][WIRE]
        self.assertTrue(url, answer)
        # the download of the same bytes works off exactly this url
        self.assertIn("record.xml", url)
        download = self.api_client().get(url)
        self.assertEqual(status, 200)
        # the media answer is a FileResponse — its bytes are the stream
        self.assertEqual(b"".join(download.streaming_content),
                         self.document_bytes(record))

    def test_a_record_without_a_document_answers_no_url(self):
        record = self.record(with_document=False)
        status, answer = api(
            self.api_client(), "get",
            f"/api/registry/dataset-metadata/{record.pk}")
        self.assertEqual(status, 200, answer)
        self.assertIsNone(answer["data"]["attributes"][WIRE])


class RawSourceWriteTests(SourceApiMixin, TestCase):
    """The accepted write: submitted document serves, mapped values land."""

    def test_a_raw_write_serves_the_submitted_document(self):
        record = self.record()
        # the editor's text carries a foreign (old) dateStamp — the header
        # is the row's, never the submitter's
        submitted = with_element_text(
            self.doc, "//*[local-name()='dateStamp']"
            "/*[local-name()='DateTime']", "2001-02-03T00:00:00")
        submitted = with_element_text(
            submitted, title_path(), "Nach der Kuratie im Quelltext")

        status, answer = self.patch_source(record, submitted.decode("utf-8"))
        self.assertEqual(status, 200, answer)
        record.refresh_from_db()

        # what the rules saw is what serves: the edited title, and only this
        # record, exactly once
        values = served_values(record)
        self.assertEqual(values["title"], "Nach der Kuratie im Quelltext")
        self.assertEqual(str(values["file_identifier"]).strip(), self.fid)
        root = etree.fromstring(self.document_bytes(record))
        self.assertEqual(len(root.xpath(
            "//*[local-name()='MD_Metadata']")), 1)
        # the header is the ROW's: the row's identifier and the stamp THIS
        # editor save bumped (#1241 AC 2 applies to a raw write as to any)
        self.assertEqual(
            values["date_stamp"],
            timezone.localtime(record.date_stamp).replace(microsecond=0))
        self.assertTrue(record.is_customized)

    def test_content_the_form_does_not_map_serves_as_submitted(self):
        """The raw path overlays nothing from the row onto the document."""
        record = self.record()
        submitted = with_element_text(
            self.doc, "//*[local-name()='northBoundLatitude']", "50.5")
        status, answer = self.patch_source(record, submitted.decode("utf-8"))
        self.assertEqual(status, 200, answer)
        # the view published ANOTHER instance of this row — the file pointer
        # of this one is stale until refreshed
        record.refresh_from_db()
        root = etree.fromstring(self.document_bytes(record))
        self.assertEqual(
            root.xpath("//*[local-name()='northBoundLatitude']")[0].text,
            "50.5")

    def test_the_mapped_values_flow_from_the_document_into_the_row(self):
        record = self.record()
        submitted = with_element_text(
            self.doc, title_path(), "Titel aus dem Quelltext")
        submitted = with_element_text(
            submitted,
            "//*[local-name()='descriptiveKeywords']"
            "//*[local-name()='keyword']/*[local-name()='CharacterString']",
            "Kuratiertes Schlagwort")

        status, answer = self.patch_source(record, submitted.decode("utf-8"))
        self.assertEqual(status, 200, answer)
        record.refresh_from_db()
        self.assertEqual(record.title, "Titel aus dem Quelltext")
        self.assertIn("Kuratiertes Schlagwort",
                      set(record.keywords.values_list("keyword", flat=True)))
        # the document names its languages; the row carries them afterwards
        self.assertGreater(record.languages.count(), 0)

    def test_a_contact_the_document_confirms_keeps_its_row(self):
        """The FK is kept when the four mapped values agree — unmapped
        address detail of a harvested contact survives the raw write."""
        record = self.record()
        extracted = served_values(record)["metadata_contact"]
        lookup = {field: str(extracted.get(field) or "")
                  for field in _CONTACT_KEY_FIELDS}
        lookup["city"] = "Kurien-Stadt"  # a column no document can speak
        detailed = MetadataContact.objects.create(**lookup)
        record.metadata_contact = detailed
        record.save(mark_customized=False)

        status, answer = self.patch_source(record, self.doc.decode("utf-8"))
        self.assertEqual(status, 200, answer)
        record.refresh_from_db()
        self.assertEqual(record.metadata_contact_id, detailed.pk)

    def test_a_contact_the_document_changes_becomes_the_named_row(self):
        record = self.record()
        submitted = with_element_text(
            self.doc,
            "//*[local-name()='contact']//*[local-name()='organisationName']"
            "/*[local-name()='CharacterString']",
            "Andere Kuratorenstelle")
        status, answer = self.patch_source(record, submitted.decode("utf-8"))
        self.assertEqual(status, 200, answer)
        record.refresh_from_db()
        self.assertEqual(record.metadata_contact.name,
                         "Andere Kuratorenstelle")

    def test_a_field_the_document_leaves_out_keeps_the_row_value(self):
        """The screen states it: the next FORM save regenerates the mapped
        elements from the database — so a left-out element must return from
        the value that survived the raw write in the row."""
        record = self.record()
        # the corpus dataset document names no ground resolution (and the
        # column is a float — the ISO "1:100000" spelling is not its shape)
        record.ground_res = 2.5
        record.save(mark_customized=False)

        status, answer = self.patch_source(record, self.doc.decode("utf-8"))
        self.assertEqual(status, 200, answer)
        record.refresh_from_db()
        self.assertEqual(record.ground_res, 2.5)

    def test_a_record_serving_no_document_yet_accepts_its_first(self):
        """Legacy records without a stored document join the source view:
        the submitted document becomes their first served one."""
        record = self.record(with_document=False)
        submitted = with_element_text(
            self.doc, title_path(), "Erstes Dokument der Kuratie")
        status, answer = self.patch_source(record, submitted.decode("utf-8"))
        self.assertEqual(status, 200, answer)
        record.refresh_from_db()
        self.assertEqual(
            served_values(record)["title"], "Erstes Dokument der Kuratie")
        self.assertEqual(record.title, "Erstes Dokument der Kuratie")

    def test_the_last_of_two_raw_wins_unchallenged(self):
        """Last-write-wins (§7 decision 6): no token gates the second write."""
        record = self.record()
        for title in ("Rohfassung eins", "Rohfassung zwei"):
            submitted = with_element_text(self.doc, title_path(), title)
            status, answer = self.patch_source(record,
                                               submitted.decode("utf-8"))
            self.assertEqual(status, 200, (title, answer))
            record.refresh_from_db()
        self.assertEqual(record.title, "Rohfassung zwei")
        self.assertEqual(served_values(record)["title"], "Rohfassung zwei")


class RawSourceWriteRefusalTests(SourceApiMixin, TestCase):
    """Every refusal is a 400 naming the member; nothing ever changed."""

    def assert_refused(self, record, status, answer, before):
        self.assertEqual(status, 400, answer)
        record.refresh_from_db()
        self.assertEqual(self.document_bytes(record), before)

    def test_malformed_xml_is_refused_with_its_position(self):
        record = self.record()
        before = self.document_bytes(record)
        status, answer = self.patch_source(record, "<MD_Metadata><oops")
        self.assert_refused(record, status, answer, before)
        error = next(error for error in answer["errors"]
                     if WIRE in error["source"]["pointer"])
        self.assertIn("not well-formed XML", error["detail"])
        self.assertIn("line", error["detail"])
        # the parser's own detail belongs to the log, not to the curator
        self.assertNotIn("Start tag expected", error["detail"])

    def test_a_blank_document_is_refused(self):
        record = self.record()
        before = self.document_bytes(record)
        status, answer = self.patch_source(record, "   ")
        self.assert_refused(record, status, answer, before)

    def test_a_document_naming_another_record_is_refused(self):
        record = self.record()
        before = self.document_bytes(record)
        other = (ISO_DATA / "service.xml").read_bytes()
        status, answer = self.patch_source(record, other.decode("utf-8"))
        self.assert_refused(record, status, answer, before)
        error = next(error for error in answer["errors"]
                     if WIRE in error["source"]["pointer"])
        self.assertIn("fileIdentifier", error["detail"])

    def test_a_document_without_a_parseable_dateStamp_is_refused(self):
        record = self.record()
        before = self.document_bytes(record)
        submitted = document_without("dateStamp")
        status, answer = self.patch_source(record, submitted.decode("utf-8"))
        self.assert_refused(record, status, answer, before)
        error = next(error for error in answer["errors"]
                     if WIRE in error["source"]["pointer"])
        self.assertIn("dateStamp", error["detail"])

    def test_a_document_that_violates_a_profile_rule_is_refused(self):
        """#1243's validation runs over the SUBMITTED document before any
        commit: the AC's invalid document changes nothing, row or document."""
        record = self.record()
        before = self.document_bytes(record)
        submitted = document_without("title")
        status, answer = self.patch_source(record, submitted.decode("utf-8"))
        self.assert_refused(record, status, answer, before)
        self.assertIn("iso19139-title",
                      {error.get("rule") for error in answer["errors"]})

    def test_a_write_alongside_another_attribute_is_refused(self):
        """The raw write re-extracts every mapped value — a title in the
        same payload would be silently undone by it."""
        record = self.record()
        before = self.document_bytes(record)
        status, answer = self.patch_source(
            record, self.doc.decode("utf-8"), attributes={"title": "Zuviel"})
        self.assert_refused(record, status, answer, before)
        self.assertIn("/data/attributes/title",
                      [error["source"]["pointer"] for error in
                       answer["errors"]])

    def test_a_write_alongside_a_relationship_is_refused(self):
        """The json:api parser flattens `data.relationships` into the
        incoming members — the stand-alone rule sees them as attributes."""
        record = self.record()
        before = self.document_bytes(record)
        status, answer = self.patch_source(
            record, self.doc.decode("utf-8"),
            relationships={"profile": {"data": {
                "type": "MetadataProfile", "id": str(self.profile.pk)}}})
        self.assert_refused(record, status, answer, before)
        self.assertTrue(any("profile" in error["source"]["pointer"]
                            for error in answer["errors"]), answer)

    def test_a_POST_naming_the_document_is_refused(self):
        """A created record gets its first document from its fields (#1244);
        the raw write replaces a served document, so it needs a record. The
        creator grant is what lets the POST reach that guard at all — without
        the model grant the permission layer answers 403 first, which
        tests_metadata_record_writes pins separately."""
        assign_perm("registry.add_datasetmetadatarecord", self.curator)
        record_title = "Creation with a source document"
        status, answer = api(
            self.api_client(), "post", "/api/registry/dataset-metadata",
            api_body(
                attributes={
                    "title": record_title,
                    "abstract": "An abstract",
                    WIRE: self.doc.decode("utf-8")},
                relationships={
                    "metadataContact": {"data": {
                        "type": "MetadataContact",
                        "id": str(self.contact.pk)}},
                    "datasetContact": {"data": {
                        "type": "MetadataContact",
                        "id": str(self.contact.pk)}}}))
        self.assertEqual(status, 400, answer)
        self.assertTrue(any("first document" in error["detail"]
                            for error in answer["errors"]), answer)
        self.assertFalse(DatasetMetadataRecord.objects.filter(
            title=record_title).exists())

    def test_a_PUT_naming_the_document_is_not_even_routed(self):
        """The json:api detail view answers PATCH, never PUT (the
        http_method_names of #1244) — the raw write is a deliberate PATCH
        also on this ground. A 405 changes nothing, fail-closed like every
        other refusal."""
        record = self.record()
        before = self.document_bytes(record)
        status, answer = api(
            self.api_client(), "put",
            f"/api/registry/dataset-metadata/{record.pk}",
            api_body(pk=record.pk,
                     attributes={WIRE: self.doc.decode("utf-8")}))
        self.assertEqual(status, 405, answer)
        record.refresh_from_db()
        self.assertEqual(self.document_bytes(record), before)

    def test_an_empty_keywords_write_still_holds_the_choice_rows(self):
        """Guard for the re-extraction helper of #1247: keyword rows the
        document names are looked up by their unique key, never duplicated."""
        record = self.record()
        Keyword.objects.create(keyword="Kuratiertes Schlagwort")
        submitted = with_element_text(
            self.doc,
            "//*[local-name()='descriptiveKeywords']"
            "//*[local-name()='keyword']/*[local-name()='CharacterString']",
            "Kuratiertes Schlagwort")
        status, answer = self.patch_source(record, submitted.decode("utf-8"))
        self.assertEqual(status, 200, answer)
        self.assertEqual(
            Keyword.objects.filter(keyword="Kuratiertes Schlagwort").count(),
            1)


class RawSourceWritePermissionTests(SourceApiMixin, TestCase):
    """canEdit gates the source write like every other record write."""

    def test_a_write_without_the_object_grant_is_denied(self):
        record = self.record()
        before = self.document_bytes(record)
        status, answer = api(
            self.api_client(user=self.stranger), "patch",
            f"/api/registry/dataset-metadata/{record.pk}",
            api_body(pk=record.pk,
                     attributes={WIRE: self.doc.decode("utf-8")}))
        self.assertEqual(status, 403, answer)
        record.refresh_from_db()
        self.assertEqual(self.document_bytes(record), before)

    @override_settings(MRMAP_METADATA_EDITOR_WRITES_ENABLED=False)
    def test_the_closed_gate_refuses_the_source_write_too(self):
        record = self.record()
        before = self.document_bytes(record)
        status, answer = self.patch_source(record, self.doc.decode("utf-8"))
        self.assertEqual(status, 403, answer)
        self.assertIn("disabled", answer["errors"][0]["detail"])
        record.refresh_from_db()
        self.assertEqual(self.document_bytes(record), before)
