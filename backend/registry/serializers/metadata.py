class RecordPermissionsSerializerMixin(HistoryInformationSerializer):
    can_edit = SerializerMethodField()
    can_delete = SerializerMethodField()

    def create(self, validated_data):
        """A record created without a profile is an iso19139-generic one.

        The api POST is the second creation path of a record besides the
        mapper persistence; both look the seeded profile up rather than
        naming it as a column default, see MetadataProfile.generic() (#1240).
        """
        if 'profile' not in validated_data:
            generic = MetadataProfile.generic()
            if generic is not None:
                validated_data['profile'] = generic
        return super().create(validated_data)

    def get_fields(self):
        fields = super().get_fields()
        if getattr(self.context.get("view"), "action", None) == "list":
            fields.pop("can_delete", None)
        return fields

    def _sparse_fieldset(self):
        """The field names the request asks for with ``fields[<Model>]``.

        Empty when the request names none. Same mechanism as
        ``ExplorerAttributesSerializer.explorer_fields`` of the services: a
        permission answer asserted per row is only paid for by the screen
        that reads it. (#1249: the batch edit needs ``canEdit`` of every
        record it was handed, to send only what the user may edit.)
        """
        request = self.context.get("request")
        if request is None:
            return []
        return [
            undo_format_field_name(name.strip())
            for name in request.GET.get(
                f"fields[{self.Meta.model.__name__}]", "").split(",")
            if name.strip()
        ]

    def to_representation(self, instance):
        result = super().to_representation(instance)
        if (getattr(self.context.get("view"), "action", None) == "list"
                and "can_edit" not in self._sparse_fieldset()):
            result.pop("can_edit", None)
        return result

    def _can_modify(self, obj, action):
        user = self.context["request"].user
        permission = f"{obj._meta.app_label}.{action}_{obj._meta.model_name}"
        if not user.has_perm(permission):
            return False
        request = self.context["request"]
        checker = getattr(request, "record_permission_checker", None)
        if checker is None:
            checker = ObjectPermissionChecker(user)
            request.record_permission_checker = checker
        return checker.has_perm(permission, obj)

    def get_can_edit(self, obj) -> bool:
        if (getattr(self.context.get("view"), "action", None) == "list"
                and "can_edit" not in self._sparse_fieldset()):
            # the value is popped from the list answer anyway (see
            # to_representation): assert it only for the list that asked
            return False
        return self._can_modify(obj, "change")

    def get_can_delete(self, obj) -> bool:
        return self._can_modify(obj, "delete")


def _member_form(name):
    """The comparison form of one json:api member or model field name.

    A payload may name a member in any casing or separator style the parser
    tolerated; the refusal names the field regardless of how it arrived.
    """
    return re.sub(r"[^0-9a-z]", "", name.lower())


class RecordWriteSerializerMixin:
    """The create/update semantics every metadata record endpoint answers (#1241).

    The endpoint itself is the default json:api CRUD behaviour of the shared
    ``ModelViewSet`` — POST/PUT/PATCH on the record resources, no bespoke
    action endpoints (the cross-cutting decision of the #1238 review). This
    mixin carries the rules which belong to a record write and to no
    other resource:

    * a write which names a field the model pins ``editable=False``
      (``file_identifier``, ``date_stamp``, ``origin``, ``is_broken``, … — the
      read-only pinning of #1240) is answered with a 400 naming every offending
      member through ``errors[].source.pointer``, instead of the silent
      dropping a ``read_only`` DRF field performs today. Two members leave
      that set: ``xml_backup_file``, whose writable representation is declared
      below, and ``file_identifier`` on a POST — the curator names the
      identifier of the record they author (#1248), see
      :meth:`_take_creation_file_identifier`;
    * a write which names a field the record's document is READ from but the
      write mapper can not WRITE (bounding geometry, time extents, the
      citation identifier) is refused with the same 400 naming the member —
      no enabled write may leave row, ``xml_backup_file`` and CSW output
      apart (readiness clarification of #1244);
    * ``xml_backup_file`` is the one attribute whose writable representation
      this mixin declares itself: the record's raw ISO source document,
      written as the document text (#1247 — the escape hatch for what the
      form can not express, per the json:api-defaults decision of the #1238
      review). A payload naming it must name nothing else (a raw write
      replaces ALL form-mapped values; mixing it with form fields would
      silently undo them), it is only writable on an existing record, and
      the document must be well-formed XML carrying exactly this record with
      its identity header. The profile's rules run over the SUBMITTED
      document before commit; a refused write changes nothing. On save the
      document is served verbatim (header aside) and the form-mapped values
      are RE-EXTRACTED from it into the row — the screen states both.
    * the structural rules of the record's profile are asked as part of the
      normal CRUD request — the payload is validated on POST/PUT/PATCH, never
      through a separate call (§5 of the metadata-editor document). #1243
      supplies the rule content and the evaluator: PUT/PATCH run the profile's
      rules over the RESULTING ISO document — the record's stored document
      with the row's and payload's values written through the publish seam of
      #1244, in memory — and answer violations as json:api error objects
      citing the rule ids, before anything is stored. A record which serves no
      document yet (a POST, whose first document this save publishes at
      commit) has nothing for the document rules to govern at validation time;
      a rule set this version can not assess stays refused outright on every
      verb (fail-closed): an unevaluated rule set must never answer a payload
      as valid;
    * a record created through the api came from the editor: ``origin`` answers
      ``MetadataOriginEnum.EDITOR``, the value of a curator creation which the
      relation bookkeeping of #1245/#1261 already speaks, and ``is_customized``
      answers ``True`` from the first row on — the flag is the marker of content
      which was authored here instead of delivered by a catalogue, which is
      exactly what a created record is (#1248; the harvest overwrite gate itself
      compares ``date_stamp`` and stays as it is, see D7 of
      docs/metadata-identity.md). A created record carries the harvest gate's
      stamp the parsed date of an import would carry: ``date_stamp`` gets its
      creation default and the first editor update bumps it through the model
      save (see :meth:`registry.models.metadata.MetadataRecord.save`).

    The ISO 19139 document a record serves is regenerated by the publish seam
    of :mod:`registry.mappers.publish` — the one place allowed to turn model
    fields into the document (§5: no second interpretation layer). ``create``
    and ``update`` wrap their row save and :meth:`_publish_record` in one
    transaction (DRF opens none itself): a successful save is the publish
    (#1244) — fields, validation (#1243) and the document commit together or
    not at all, and a refused write changes nothing. Concurrency is
    last-write-wins (§7 decision 6): no lock is taken and no token answered;
    the last committed save serves.
    Whether a deployment opens these endpoints at all is the activation gate
    ``MRMAP_METADATA_EDITOR_WRITES_ENABLED`` (see
    :class:`registry.views.metadata.MetadataRecordWritesEnabled`), on by
    default since the round trip of this issue.
    """

    #: the source document of a raw write, validated by :meth:`validate` and
    #: published EXACTLY as the rules saw it by :meth:`update` (#1247)
    _validated_source_document = None

    #: The one member the model pins ``editable=False`` which a POST may name
    #: (#1248): the file identifier IS the record's ISO ``fileIdentifier``, so a
    #: curator authoring a record names it — that is the point of the create
    #: screen — and the answer they get for a collision is the reason the field
    #: is offered at all. It stays immutable the moment the row exists: from the
    #: second request on the read-only refusal below names it again, because
    #: ``get_or_create_metadatarecord()`` looks records up by this value and a
    #: renamed identifier is a different record to every catalogue.
    CREATION_WRITABLE_MEMBERS = frozenset({"file_identifier"})

    def get_fields(self):
        fields = super().get_fields()
        # the model pins ``xml_backup_file`` ``editable=False`` - the
        # read-only derivation of #1240 would refuse every write naming it.
        # #1247 declares the writable representation of this ONE attribute
        # here: reads keep answering the stored file's url (the answer of
        # the autogenerated FileField, byte-identical), writes take the
        # document text. One declaration for all three record kinds.
        model_field = self.Meta.model._meta.get_field(SOURCE_DOCUMENT_MEMBER)
        fields[SOURCE_DOCUMENT_MEMBER] = RecordSourceDocumentField(
            required=False,
            allow_blank=False,
            trim_whitespace=False,
            label=model_field.verbose_name,
            help_text=model_field.help_text,
        )
        return fields

    def validate(self, attrs):
        attrs = super().validate(attrs)
        self._reject_non_writable_members()
        self._reject_non_roundtrippable_members()
        self._validate_source_document(attrs)
        if self.instance is None:
            self._take_creation_file_identifier(attrs)
        self._validate_profile_rules(attrs)
        return attrs

    def create(self, validated_data):
        """The api POST is an editor's creation; the record says so afterwards.

        ``origin`` and ``is_customized`` are ``editable=False`` on the model —
        the serializer can not be asked to write them and no payload may name
        them (see :meth:`_reject_non_writable_members`); the server stamps them
        here, where a server-assigned value belongs. ``is_customized`` is on
        because a record which comes into existence at the curator's desk is
        curated content from the first row on, it is no catalogue's copy to
        begin with (#1248). The file identifier the payload named rode in with
        :meth:`_take_creation_file_identifier`; without one the model's
        ``uuid4`` default generates it. The publish then generates the record's
        first document: a created record without one would fail the CSW page
        it appears in, so POST commits the skeleton-derived document together
        with the row (#1244) and :func:`registry.mappers.publish._force_header`
        writes the row's identifier into that document.
        """
        validated_data["origin"] = MetadataOriginEnum.EDITOR.value
        validated_data["is_customized"] = True
        # a POST naming the source document is refused by
        # _validate_source_document already; popping keeps the write path of
        # the FileField free of a text its descriptor would read as a name
        validated_data.pop(SOURCE_DOCUMENT_MEMBER, None)
        with transaction.atomic():
            record = super().create(validated_data)
            return self._publish_record(record, validated_data)

    def update(self, instance, validated_data):
        """A successful PUT/PATCH is the publish of the edited record (#1244).

        The row save of ``super().update()`` set ``is_customized`` and bumped
        ``date_stamp`` (the harvest overwrite gate's side effects, #1241); the
        publish regenerates the served document from the SAVED row inside the
        same transaction, so the document carries the bumped stamp and a
        rollback leaves both at their previous state.

        A write which named the source attribute takes the other publish of
        the same seam (#1247): the row save still flags and bumps the record
        (a raw write is an edit like any other), then the VALIDATED
        submitted document is stored as the served document and its mapped
        values re-extracted into the row - last-write-wins, no token, no
        lock, exactly like the form path.
        """
        # the validated text is no file name; it is published from
        # self._validated_source_document, which carries the bytes the
        # rules saw - never a re-derivation
        validated_data.pop(SOURCE_DOCUMENT_MEMBER, None)
        with transaction.atomic():
            record = super().update(instance, validated_data)
            if self._validated_source_document is not None:
                return self._publish_source_document(record)
            return self._publish_record(record, validated_data)

    def _publish_record(self, record, validated_data):
        try:
            return publish_document(record, validated_data)
        except PublishRefused as refused:
            logger.error(
                "the publish of record %s was refused: %s",
                record.pk, refused)
            raise ValidationError(_(
                "The ISO document served for this record could not be "
                "regenerated from its stored fields; the write is refused "
                "so that the served document never disagrees with the "
                "record."))

    def _publish_source_document(self, record):
        """Store the raw document the validation of this save accepted.

        The bytes are the ones the profile rules were run over, header
        included (:meth:`_validate_source_document` ran the whole
        construction before DRF saved anything); a refusal here can only
        come from storage or the model, and rolls the whole write back.
        """
        document, values = self._validated_source_document
        self._validated_source_document = None
        try:
            return publish_source_document(record, document, values)
        except PublishRefused as refused:
            logger.error(
                "the raw source document of record %s could not be "
                "published: %s", record.pk, refused)
            raise ValidationError(_(
                "The submitted source document could not be published as "
                "the record's document; the write is refused and nothing "
                "changed."))

    def _reject_non_writable_members(self):
        """Refuse a payload which names a field the model refuses to write.

        A DRF ``read_only`` field is dropped from the incoming data in silence;
        the json:api answer for such a write is a 400 which names the member
        (acceptance criteria of #1241). Which members those are is not a second
        list to maintain: every concrete model field with ``editable=False``
        which the serializer answers at all is read-only in the OpenAPI schema
        of #1240 and refused here — one derivation, one truth. The truth has
        two departures, both declared by this very mixin: the raw source
        document of #1247, whose writable representation is the serializer
        field this class installs for every record kind, and the file
        identifier of a creation (#1248), see
        :attr:`CREATION_WRITABLE_MEMBERS`.
        """
        incoming = getattr(self, "initial_data", None)
        if not isinstance(incoming, dict):
            return
        # the primary key is the resource's identity: a json:api PATCH/PUT
        # names it in `data.id` by the spec, it is not a writable field the
        # payload is offered
        pk_name = self.Meta.model._meta.pk.name
        read_only = {
            field.name for field in self.Meta.model._meta.concrete_fields
            if not field.editable and field.name != pk_name
        } & set(self.get_fields().keys()) - {SOURCE_DOCUMENT_MEMBER}
        if self.instance is None:
            # a creation authors its record and names its identifier (#1248);
            # from the second request on the field is refused again
            read_only -= set(self.CREATION_WRITABLE_MEMBERS)
        forms = {_member_form(name): name for name in read_only}
        offenders = sorted({
            forms[_member_form(member)]
            for member in incoming
            if _member_form(member) in forms
        })
        if offenders:
            raise ValidationError({
                name: _("This field is read-only and can not be written.")
                for name in offenders
            })

    def _take_creation_file_identifier(self, attrs):
        """The file identifier a creation names, asked of the database first (#1248).

        The column is ``editable=False``, so DRF keeps the value out of the
        validated data: what the curator typed has to be read from the request
        the same way :meth:`_reject_non_writable_members` reads its members —
        the json:api parser leaves members in their wire casing, which is why
        both compare through :func:`_member_form`.

        Three answers, none of which has written a byte of the record yet:

        * the payload names no file identifier, or a blank one: the model's
          ``uuid4`` default generates it — a curator who does not care about the
          identifier of their record gets the server-generated uuid the AC
          asks for;
        * the value belongs to no row of this record type: it rides on
          ``attrs`` into the row, and the publish writes that value into the
          document's ``gmd:fileIdentifier``, so row and served document agree
          from the first save on;
        * a row of this record type carries it already: a 400 naming
          ``file_identifier``, which the json:api answer spells as
          ``errors[].source.pointer`` on the field the curator typed — the
          pointer shape #1241 established for a refused member. The question is
          asked of the same table the per record type constraint of
          ``%(app_label)s_%(class)s_unique_file_identifier`` guards, because the
          alternative is an ``IntegrityError`` from inside the publish's
          transaction: a 500 which names no field and explains nothing.
        """
        incoming = getattr(self, "initial_data", None)
        if not isinstance(incoming, dict):
            return
        forms = {_member_form(name) for name in self.CREATION_WRITABLE_MEMBERS}
        named = [value for member, value in incoming.items()
                 if _member_form(member) in forms]
        if not named:
            return
        value = named[0]
        if not isinstance(value, str):
            raise ValidationError({
                "file_identifier": _("The file identifier must be a text.")})
        identifier = value.strip()
        if not identifier:
            # left blank on purpose: the server generates the identifier
            return
        max_length = self.Meta.model._meta.get_field(
            "file_identifier").max_length
        if len(identifier) > max_length:
            raise ValidationError({
                "file_identifier": _(
                    "The file identifier is too long; it may hold at most "
                    "%(max_length)s characters.") % {
                        "max_length": max_length}})
        if self.Meta.model.objects.filter(
                file_identifier=identifier).exists():
            raise ValidationError({
                "file_identifier": _(
                    "A record with this file identifier already exists. The "
                    "file identifier is the identifier of the record inside "
                    "its ISO document and must be unique.")})
        attrs["file_identifier"] = identifier

    def _reject_non_roundtrippable_members(self):
        """Refuse a payload writing a field the document can not carry back.

        The readiness clarification of #1244 (2026-11-12): no enabled public
        write path may leave model fields, ``xml_backup_file`` and the CSW
        output out of sync. The fields the configs READ from the record's
        document but the write mapper of #1242 can not WRITE (the citation
        identifier) would commit into the row while the served document
        silently kept its old value — the one sync gap a successful save could
        no longer heal. Refusing them is the
        same fail-closed posture as a rule set this version can not evaluate,
        and the set is derived from the configs (see
        :func:`registry.mappers.publish.non_roundtrippable_fields`), not kept
        as a second list.
        """
        incoming = getattr(self, "initial_data", None)
        if not isinstance(incoming, dict):
            return
        fields = self.get_fields()
        pk_name = self.Meta.model._meta.pk.name
        writable = {name for name, field in fields.items()
                    if name != pk_name and not field.read_only}
        refused = non_roundtrippable_fields(self.Meta.model, writable)
        forms = {_member_form(name): name for name in refused}
        offenders = sorted({
            forms[_member_form(member)]
            for member in incoming
            if _member_form(member) in forms
        })
        if offenders:
            raise ValidationError({
                name: _(
                    "This field is read out of the record's ISO document but "
                    "the document has no writable mapping for it; accepting "
                    "this write would leave the served document behind the "
                    "record.")
                for name in offenders
            })

    def _validate_source_document(self, attrs):
        """Validate a submitted raw source document before anything is saved.

        Runs when the payload names ``xml_backup_file``; the accepted
        construction is stored on the serializer so that :meth:`update`
        publishes EXACTLY the bytes the rules were run over — the posture of
        :meth:`_resulting_document`: one construction, evaluated and served,
        never a second which could disagree. Every refusal is a json:api 400
        naming the offending member; nothing is stored.

        The rules a submitted text must satisfy, each the fail-closed posture
        of the form write:

        * it is written onto an EXISTING record — a POST has no document to
          replace, its first document comes from its fields (#1244); the PUT
          never reaches this guard at all — the detail view answers PATCH,
          not PUT (#1244's http_method_names), which makes the raw write a
          deliberate PATCH, as the screen sends it;
        * it stands ALONE: the raw write re-extracts every form-mapped value
          from the document, so any other member of the same payload would
          be silently undone — refusing the combination is the only answer
          which never saves a value the served document contradicts;
        * it is well-formed XML — the position is a fact about the curator's
          own text, the detail of the parser belongs to the log (#1243's
          posture against GeoNetwork's raw engine errors);
        * it carries exactly this record with a parseable identity header,
          the header then forced to the row's values, and its profile rules
          run next over the very document the save would publish
          (:meth:`_validate_profile_rules` reads the stored construction).
        """
        self._validated_source_document = None
        if SOURCE_DOCUMENT_MEMBER not in attrs:
            return
        text = attrs[SOURCE_DOCUMENT_MEMBER]
        if self.instance is None:
            raise ValidationError({
                SOURCE_DOCUMENT_MEMBER: _(
                    "A created record receives its first document from its "
                    "fields; the raw source document is written onto an "
                    "existing record.")})
        incoming = getattr(self, "initial_data", None)
        if isinstance(incoming, dict):
            # the resource identity members of the envelope (json:api names
            # the pk in `data.id`) accompany any write; they are not payload
            pk_forms = {
                _member_form(self.Meta.model._meta.pk.name),
                _member_form(SOURCE_DOCUMENT_MEMBER),
                "id", "type",
            }
            offenders = sorted({
                member for member in incoming
                if _member_form(member) not in pk_forms
            })
            if offenders:
                raise ValidationError({
                    name: _(
                        "The raw source document replaces every form-mapped "
                        "value of the record; it must be written on its own, "
                        "without other attributes.")
                    for name in offenders})
        try:
            etree.fromstring(text.encode("utf-8"))
        except XMLSyntaxError as error:
            logger.info(
                "a raw source document write on record %s carried "
                "malformed XML: %s", self.instance.pk, error)
            raise ValidationError({
                SOURCE_DOCUMENT_MEMBER: _(
                    "The source document is not well-formed XML (line "
                    "%(line)s, column %(column)s).") % {
                        "line": error.lineno, "column": error.position[1]}})
        try:
            document, values = build_source_document(
                self.instance, text.encode("utf-8"))
        except PublishRefused as refused:
            logger.info(
                "the source document write on record %s was refused: %s",
                self.instance.pk, refused)
            raise ValidationError({
                SOURCE_DOCUMENT_MEMBER: _(
                    "The submitted document can not become this record's "
                    "source document: it must carry exactly this record - "
                    "identified by its fileIdentifier, with a parseable "
                    "dateStamp - as the kind of ISO 19139 document the "
                    "record is.")})
        self._validated_source_document = (document, values)

    def _validate_profile_rules(self, attrs):
        """Run the profile's ISO rule set over the resulting document (#1243).

        The profile which governs the write is the one the payload names, the
        one the record under update carries, or the generic profile a created
        record falls back to (the creation paths of #1240). A rule set this
        version can not assess is refused on every verb (the fail-closed rule
        #1241 shipped and #1243 keeps for rule shapes it can not evaluate).
        On PUT/PATCH the rules run over the document the save WOULD produce:
        the record's stored document with the row's values, this payload
        included, written through the publish seam of #1244, in memory
        (readiness clarification: the same mapper semantics, never a
        disconnected representation). A record which serves no document yet
        (a POST, whose first document this very save generates at commit) has
        nothing for the document rules to govern at validation time — the
        posture #1243 shipped; it joins the rule regime with its next write,
        which evaluates the document its predecessor committed. Violations of
        `error` severity refuse the write with one json:api error object per
        finding, warnings ride along in that answer but never refuse alone —
        the document stays untouched either way, this runs before DRF saves
        anything.
        """
        profile = attrs.get("profile", None)
        if profile is None:
            profile = (self.instance.profile if self.instance is not None
                       else MetadataProfile.generic())
        rules = (profile.rules or []) if profile is not None else []
        if not rules:
            return
        if not all(assessable_rule(rule) for rule in rules):
            raise ValidationError(_(
                "The profile of this record names structural rules which this "
                "version can not evaluate; the write is refused instead of "
                "skipping the validation."
            ))
        if self.instance is None:
            # POST: no document is served for the created record until this
            # save publishes one at commit — nothing to validate over yet
            return
        document = self._resulting_document(attrs)
        if document is None:
            # the record carries no readable document yet: same posture as
            # POST — its first served document arrives with this save
            return
        findings = evaluate_rules(rules, document)
        if not any(f.severity == "error" for f in findings):
            # warnings never block a save; the editor rail shows them from
            # the rules it fetched with the record (#1245)
            return
        raise ValidationError({
            "non_field_errors": findings_to_errors(findings),
        })

    def _resulting_document(self, attrs):
        """The document bytes the save of this payload would produce.

        The one construction of the publish seam (see
        :func:`registry.mappers.publish.build_resulting_document`), in memory:
        what validation evaluates here is what the publish persists after the
        save — modulo the stamp the save itself bumps. Answers None for a
        record without a readable stored document; the write is refused
        fail-closed when the record can not be located in its own document or
        the write mapper refuses the combination: without an assessment the
        payload must not pass.
        A RAW write (#1247) answers the construction its
        :meth:`_validate_source_document` already built and stored: the
        SUBMITTED document with the row's header - what is evaluated is what
        the save publishes, and a raw save publishes the submitted document,
        not a row-derived one.
        """
        submitted = (self._validated_source_document[0]
                     if self._validated_source_document is not None
                     else None)
        if submitted is not None:
            return submitted
        try:
            return build_resulting_document(
                self.instance, attrs, seed_missing=False)
        except PublishRefused:
            raise self._unassessable_document_error()

    @staticmethod
    def _unassessable_document_error():
        return ValidationError(_(
            "The structural rules of this record's profile could not be "
            "assessed against its ISO document; the write is refused "
            "instead of skipping the validation."
        ))


class BoundingGeometryField(GeometryField):
    """The geometry member of the editor's extent widget (#1246).

    The read side answers the column as GeoJSON; the write side must hand
    the proxy the collection type the column is — the autogenerated field
    would set the parsed POLYGON straight onto the MULTIPOLYGON column and
    die in the proxy's ``TypeError``. A single geometry from the map widget
    is promoted, anything already a collection passes through.
    """

    def to_internal_value(self, data):
        geometry = super().to_internal_value(data)
        if geometry is not None and not isinstance(geometry, MultiPolygon):
            return MultiPolygon([geometry])
        return geometry


