#!/usr/bin/env python3
"""Canonical version guard (#1579): one version source, no handwritten copies.

Run from the repository root:  python3 scripts/test_canonical_version.py
Standard library only, no docker, no git, no network. Exit 0 = every check
passed, 1 = a check failed, 2 = the harness itself could not run.

Why this guard exists
---------------------
#1579 made the root ``VERSION`` file the single canonical application version
and turned every consumer into a projection of it: the committed
``backend/MrMap/version.py`` (generated by ``scripts/canonical_version.py``),
the frontend bundle (``frontend/vite.config.mjs`` reads the file at build
time), and the Sphinx docs (which import ``MrMap.VERSION``). The failure mode
this suite refuses is the old one: a second source that someone edits, a
consumer that quietly disagrees, or a build that proceeds without a version.
The QA containers cannot see both sides of the split at once - the backend
container binds only ``./backend``, the frontend container only ``./frontend``
- so the only place the projections can be compared with the canonical file
is on the host, next to a full checkout, which is exactly where this suite
runs (``scripts/check_repo_tooling.sh``, CI job script-tests).

What it checks
--------------
1. The validator itself: strict SemVer 2.0.0 (prerelease and +build metadata
   accepted; prefixes, leading zeros, empty sections refused), and the
   write/check cycle against a throw-away fixture directory - missing file,
   invalid file, drifted projection and hand-edited projection all fail.
2. The live repository: the canonical file is valid and the committed backend
   projection is exactly what the generator writes for it; ``MrMap/__init__.py``
   carries no literal version any more; the frontend build reads and injects
   the canonical file and stamps a revision; the nginx image carries the file
   to the exact path the config reads; the compose files keep the mounts and
   the revision argument the build depends on; the docs conf still imports
   ``MrMap.VERSION`` instead of a literal; and ``frontend/package.json``
   still carries no second version field of its own.
"""

import json
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import canonical_version as cv  # noqa: E402

REPO = Path(__file__).resolve().parent.parent

RESULTS = []


def check(name, ok, detail=""):
    RESULTS.append((name, bool(ok), detail))


VALID_VERSIONS = [
    '0.1.0', '1.2.3', '10.20.30',
    '0.2.0-rc.1',                      # prerelease
    '1.0.0-alpha.1+exp.sha.5114f85',   # prerelease + build metadata
    '0.1.0+9f8e7d6',                   # exact build revision
]

INVALID_VERSIONS = [
    '', '   ', 'v0.1.0', '0.1', '1.2.3.4', '1.2.3-', '1.2.3+',
    '01.2.3', '1.02.3', '1.2.3-01', '1.2.3+build_underscore',
    '1.2.3\n4.0.0', 'release-0.1.0',
]


def validation_checks():
    for version in VALID_VERSIONS:
        check(f'accept {version!r}',
              bool(cv.SEMVER_PATTERN.match(version)))
    for version in INVALID_VERSIONS:
        check(f'reject {version!r}',
              not cv.SEMVER_PATTERN.match(version))


def fixture_checks():
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        check('missing VERSION is an error',
              isinstance(_error(root), cv.VersionError))

        (root / cv.VERSION_FILE).write_text('nope\n', encoding='utf-8')
        check('invalid VERSION is an error',
              isinstance(_error(root), cv.VersionError))

        (root / cv.VERSION_FILE).write_text('0.2.0-rc.1+9f8e7d6\n',
                                            encoding='utf-8')
        check('prerelease + revision passes', _error(root) is None)
        check('fresh root has no projection yet',
              any(cv.PROJECTION in problem
                  for problem in cv.check(root)))

        cv.write_projection(root, cv.read_version(root))
        check('write then check is clean', cv.check(root) == [])

        (root / cv.VERSION_FILE).write_text('0.2.0\n', encoding='utf-8')
        problems = cv.check(root)
        check('bumped VERSION without --write fails',
              any('does not match' in problem for problem in problems),
              '; '.join(problems))

        cv.write_projection(root, cv.read_version(root))
        hand = (root / cv.PROJECTION).read_text(encoding='utf-8')
        (root / cv.PROJECTION).write_text(
            hand.replace('0.2.0', '9.9.9'), encoding='utf-8')
        check('hand-edited projection fails',
              any('does not match' in problem
                  for problem in cv.check(root)))


def _error(root):
    try:
        cv.read_version(root)
    except cv.VersionError as error:
        return error
    return None


def live_repo_checks():
    problems = cv.check(REPO)
    check('root VERSION and projections are coherent',
          not problems, '; '.join(problems))

    init_py = (REPO / 'backend/MrMap/__init__.py').read_text(
        encoding='utf-8')
    check('MrMap/__init__.py carries no literal version',
          "__version__ = VERSION" in init_py
          and "from .version import VERSION" in init_py
          and "version import" in init_py)

    vite = (REPO / 'frontend/vite.config.mjs').read_text(encoding='utf-8')
    check('vite reads the canonical file next to the frontend dir',
          "new URL('../VERSION', import.meta.url)" in vite)
    check('vite injects the version and the revision',
          "'import.meta.env.VITE_APP_VERSION'" in vite
          and "'import.meta.env.VITE_BUILD_REVISION'" in vite)
    check('vite fails on a missing or invalid version',
          'missing' in vite and 'invalid version' in vite
          and 'throw new Error' in vite)

    nginx = (REPO / 'docker/nginx/nginx.Dockerfile').read_text(
        encoding='utf-8')
    check('the nginx image carries VERSION where vite reads it',
          'COPY ./VERSION /VERSION' in nginx)
    check('the nginx image stamps the build revision into the bundle',
          'ARG MRMAP_BUILD_REVISION' in nginx
          and 'MRMAP_BUILD_REVISION="${MRMAP_BUILD_REVISION}" npm run build'
          in nginx)

    compose_base = (REPO / 'docker-compose.yml').read_text(encoding='utf-8')
    check('compose passes the deployer revision to the frontend build',
          'MRMAP_BUILD_REVISION=${MRMAP_BUILD_REVISION:-}' in compose_base)

    compose_dev = (REPO / 'docker-compose.dev.yml').read_text(
        encoding='utf-8')
    check('frontend-tests sees the canonical file at ../VERSION',
          'source: ./VERSION' in compose_dev
          and 'target: /opt/mrmap/VERSION' in compose_dev)

    conf = (REPO / 'docs/source/conf.py').read_text(encoding='utf-8')
    check('Sphinx consumes the version through MrMap',
          'from MrMap import VERSION' in conf
          and 'release = VERSION' in conf)

    package = json.loads(
        (REPO / 'frontend/package.json').read_text(encoding='utf-8'))
    check('frontend/package.json carries no second version field',
          'version' not in package)


def main():
    try:
        if not (REPO / 'frontend/vite.config.mjs').exists():
            raise RuntimeError(
                'run from the repository root (no frontend/ found)')
        validation_checks()
        fixture_checks()
        live_repo_checks()
    except Exception as error:  # noqa: BLE001 - harness failure, not a check
        print(f'harness: {error}', file=sys.stderr)
        return 2

    width = max((len(name) for name, _, _ in RESULTS), default=0)
    failed = [(name, detail) for name, ok, detail in RESULTS if not ok]
    for name, ok, detail in RESULTS:
        line = f"{'PASS' if ok else 'FAIL'}  {name:<{width}}"
        if not ok and detail:
            line += f'   <- {detail}'
        print(line)
    if failed:
        print(f'FAILED ({len(failed)} of {len(RESULTS)} checks)',
              file=sys.stderr)
        return 1
    print(f'OK ({len(RESULTS)} checks)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
