#: the json:api member carrying a record's raw ISO source document (#1247).
#: Decided in the review of the design document (r4537341050): the raw-XML
#: write follows the json:api CRUD defaults - the source document is a
#: WRITABLE attribute of the record resource, PATCHed like any other
#: attribute and validated by the same on-save validation (#1243) before
#: anything commits. No bespoke action endpoint. Its readable answer is
#: unchanged (the url of the stored media file, as FileFields answer across
#: this api and as the download of the same bytes relies on); only its
#: WRITABLE representation is new: the document text.
SOURCE_DOCUMENT_MEMBER = "xml_backup_file"


class RecordSourceDocumentField(CharField):
    """The record's ISO source document: read as the file url, written as text.

    Reads keep answering exactly what the autogenerated ``FileField`` of
    ``xml_backup_file`` answered - the url of the stored media file - so the
    download of the same bytes (and every consumer of the attribute) is
    untouched. Writes take the document text; what a submitted text must
    satisfy before it may become the served document is decided by the
    serializer's validation, not here. ``trim_whitespace`` is off: leading
    whitespace (the xml declaration) is document content, and a blank write
    names nothing to store.
    """

    default_error_messages = {
        "invalid": _(
            "The source document must be sent as the document text."),
    }

    def to_representation(self, value):
        # byte-identical to the FileField the model autogenerated: an empty
        # field answers no url, a stored one answers the media url made
        # absolute against the request, exactly as DRF's FileField does
        if not value:
            return None
        url = value.url
        request = self.context.get("request", None)
        return request.build_absolute_uri(url) if request else url


