def cmd_load(args):
    """Emit one record per workload fixture, from the timings a run produced.

    The timings come from a fixture JSON written by the Django bench suite (or by
    any other runner which speaks the same shape); this command never imports
    Django, never opens a database connection and never starts a worker, which is
    what lets the whole report path run offline and in CI.
    """
    planned, mode = resolve_repeats(args.repeats)
    args.repeats_planned = planned if mode is None else args.repeats_cap
    args.repeats_mode = mode or "fixed"
    args.repeat = args.repeat if args.repeat is not None else 1
    if not args.arm and not args.fixture and not args.fixture_dir:
        raise SystemExit("load wants --arm plus a workload to read (--fixture or "
                         "--fixture-dir); a record without both would state a "
                         "measurement with nothing measured")
    records = []
    for path in discover_fixture_files(args):
        fixture = read_fixture(path)
        record = build_record(args, fixture)
        record["source_fixture"] = path
        records.append(record)
    digest = records[0]["digest"] if records else None
    # Checked before anything is written, and against what the output already
    # holds: the runner loads one file per invocation, so a workload file left by
    # an earlier run would land in the same report a second time. `cv` is what
    # the stability floor and the gate read, and it is assembled from these rows
    # - a cell counted twice is not more evidence, it is one reading counted
    # twice, and it manufactures the figure the epic says a reviewer can look up.
    seen = {}
    if args.out and os.path.isfile(args.out) and os.path.getsize(args.out):
        for prior in load_records(args.out):
            seen.setdefault((prior.get("digest"), prior.get("arm"),
                             prior.get("repeat")),
                            prior.get("source_fixture") or args.out)
    for record in records:
        key = (record["digest"], record["arm"], record.get("repeat"))
        if key in seen:
            raise SystemExit(
                "%s repeats %s of arm %r for the same workload as %s - two "
                "readings of one cell of the report, name them apart"
                % (record.get("source_fixture"), record.get("repeat"),
                   record["arm"], seen[key]))
        seen[key] = record.get("source_fixture")
    for record in records:
        append_record(args.out, record)
    first = records[0]
    print("family=%s arm=%s repeat=%s/%s fixtures=%d digest=%s" % (
        first["family"], first["arm"], first["repeat"],
        first["repeats_planned"], len(records), digest), file=sys.stderr)
    return 0


def cmd_record(args):
    """Append one already-built JSON record, after the same validation as `load`.

    The seam for a runner which produces its own JSON - the heavy backlog benchmark
    and the CI report step both land here rather than reimplementing the checks.
    """
    with open(args.infile, encoding="utf-8") as handle:
        payload = json.load(handle)
    rows = payload if isinstance(payload, list) else [payload]
    for index, row in enumerate(rows, 1):
        validate_record(row, source="record[%d]" % index)
        if "digest" not in row:
            finalize_record(row)
        append_record(args.out, row)
    print("recorded %d record(s) into %s" % (len(rows), args.out or "stdout"),
          file=sys.stderr)
    return 0


def cmd_report(args):
    """The arm table of a JSONL, one row per family/arm/scale/repeat.

    Durations print as ``p50/p95/p99`` with the sample count in the cell, so a
    reader cannot mistake a p50 over three samples for one over three hundred.
    """
    records = filter_records(load_records(args.infile), args.family, args.arm,
                             args.scale)
    # the repeatability of an arm is a property of its repeats together, so it is
    # computed over the group and printed in every row of that group
    cv_of = {}
    for record in records:
        key = (record["family"], record["arm"], record.get("scale"),
               record.get("seed"), record.get("digest"))
        cv_of.setdefault(key, []).append(
            (record.get("durations") or {}).get("active", {}).get("p50"))
    cv_by_group = {key: coefficient_of_variation([v for v in values if v is not None])
                   for key, values in cv_of.items()}
    if not records:
        raise SystemExit("no record matches family=%s arm=%s scale=%s"
                         % (args.family or "*", args.arm or "*",
                            args.scale or "*"))
    header = "%-28s %-18s %-8s %5s %6s %22s %14s %14s %8s %8s" % (
        "family", "arm", "scale", "n", "rep", "active p50/p95/p99 (s)",
        "queue p50 (s)", "e2e p50 (s)", "slot-s", "cov")
    print(header)
    print("-" * len(header))
    for record in sorted(records, key=lambda r: (r["family"], r["arm"],
                                                 str(r.get("scale")),
                                                 r.get("repeat", 1))):
        durations = record.get("durations") or {}
        active = durations.get("active") or {}
        queue = durations.get("queue") or {}
        end_to_end = durations.get("end_to_end") or {}
        pressure = record.get("pressure") or {}
        slot = (pressure.get("occupied_slot_seconds") or {}).get("value")
        cov = cv_by_group.get(
            (record["family"], record["arm"], record.get("scale"),
             record.get("seed"), record.get("digest")))
        print("%-28s %-18s %-8s %5s %6s %22s %14s %14s %8s %8s" % (
            record["family"], record["arm"], record.get("scale") or "-",
            active.get("n", 0),
            "%s/%s" % (record.get("repeat", 1), record.get("repeats_planned", 1)),
            cell(active, ["p50", "p95", "p99"]),
            cell(queue, ["p50"]),
            cell(end_to_end, ["p50"]),
            "-" if slot is None else round(slot, 3),
            "-" if cov is None else "%.3f" % cov))
    print()
    for record in sorted(records, key=lambda r: (r["family"], r["arm"])):
        print("# %s / %s / %s repeat %s  seed=%s digest=%s revision=%s" % (
            record["family"], record["arm"], record.get("scale") or "-",
            record.get("repeat", 1), record.get("seed"), record.get("digest"),
            record.get("revision")))
        print("  evidence=%s  notes=%s" % (
            (record.get("quality") or {}).get("evidence"),
            record.get("notes") or "-"))
        outcomes = record.get("outcomes") or {}
        if outcomes:
            print("  outcomes=%s" % format_outcomes(outcomes))
        uncertain = record.get("uncertain") or {}
        if uncertain:
            print("  uncertain=%s" % json.dumps(uncertain, sort_keys=True))
        group_cov = cv_by_group.get(
            (record["family"], record["arm"], record.get("scale"),
             record.get("seed"), record.get("digest")))
        missing = missing_coverage(record, group_cov)
        if missing:
            print("  missing coverage=%s" % ", ".join(missing))
        quality = record.get("quality") or {}
        for key in ("retention_truncated", "worker_loss", "worker_loss_note"):
            if quality.get(key):
                print("  %s=%s" % (key, quality[key]))
    return 0


def cell(block, keys):
    if not block or not block.get("n"):
        return "-"
    parts = []
    for key in keys:
        value = block.get(key)
        parts.append("-" if value is None else str(value))
    return "%s(%d)" % ("/".join(parts), block.get("n", 0))


def format_outcomes(outcomes):
    rows = []
    for name in OUTCOME_ORDER + tuple(sorted(k for k in outcomes
                                             if k not in OUTCOME_ORDER)):
        block = outcomes.get(name)
        if block is None:
            continue
        rows.append("%s=%s" % (name, block["count"] if isinstance(block, dict)
                               else block))
    return " ".join(rows) if rows else "-"


def missing_coverage(record, cv=None):
    """What this record cannot answer - stated, not silently absent.

    The acceptance criterion is that missing coverage is *labelled*; this is the
    single place the labels come from, so the report and the gate agree.
    """
    missing = []
    durations = record.get("durations") or {}
    if not (durations.get("queue") or {}).get("n"):
        missing.append("queue_wait_unmeasured")
    if not (durations.get("end_to_end") or {}).get("n"):
        missing.append("end_to_end_unmeasured")
    active = durations.get("active") or {}
    if active.get("n") and active.get("p95") is None:
        missing.append("p95_under_sampled(%s<%s)"
                       % (active.get("n"), P95_MIN_SAMPLES))
    if active.get("n") and active.get("p99") is None:
        missing.append("p99_under_sampled(%s<%s)"
                       % (active.get("n"), P99_MIN_SAMPLES))
    if cv is None:
        missing.append("repeatability_unmeasured")
    if (record.get("pressure") or {}).get("broker") is None:
        missing.append("broker_pressure_unmeasured")
    if (record.get("pressure") or {}).get("resource") is None:
        missing.append("resource_pressure_unmeasured")
    if (record.get("instrumentation") or {}).get("overhead_seconds") is None:
        missing.append("instrumentation_overhead_unmeasured(#1389)")
    if (record.get("correlation") or {}).get("slow_task") is None:
        missing.append("slow_task_correlation_unmeasured(#1390)")
    return missing


def cmd_compare(args):
    """Before/after for two named arms, refusing anything that is not comparable.

    Same workload digest or no verdict: a baseline of 100 records against a
    candidate of 10 000 is a story, not a regression report.
    """
    records = load_records(args.infile)
    selection = dict(family=args.family, scale=args.scale)
    baseline = select_arm(records, args.baseline, selection, "baseline")
    candidate = select_arm(records, args.candidate, selection, "candidate")
    digests = {baseline[0]["digest"], candidate[0]["digest"]}
    if len(digests) != 1:
        raise SystemExit(
            "refusing to compare: the two arms describe different workloads "
            "(digest %s vs %s). Same family, fixture, scale, records, seed and "
            "environment are required." % tuple(sorted(digests)))
    verdict = build_verdict(args.baseline, args.candidate, baseline, candidate,
                            args.now)
    print(json.dumps(verdict, indent=2, sort_keys=True))
    if args.out:
        with open(args.out, "w", encoding="utf-8") as handle:
            handle.write(canonical(verdict) + "\n")
    return 0


def select_arm(records, arm, selection, role):
    rows = [r for r in records if r.get("kind", "load") == "load"
            and r.get("arm") == arm]
    for key, value in selection.items():
        if value:
            rows = [r for r in rows if r.get(key) == value]
    if not rows:
        raise SystemExit("no %s record for arm %r%s"
                         % (role, arm,
                            " in family %r" % selection["family"]
                            if selection.get("family") else ""))
    return rows


def arm_summary(rows):
    """The numbers one arm answers: repeat medians, percentiles over all samples.

    Repeats are the unit of repeatability (``cv_active`` over their medians); the
    percentiles pool every sample of every repeat, because "how slow can it get"
    is a question over all attempts, not over one repeat's worth. Where a record
    carried only aggregates (the bounded-artifact shape), the pooling falls back
    to those aggregates and the block says ``derived`` - an aggregate of
    aggregates is not the same statement as a percentile over attempts, and the
    reader is told which one it is looking at.
    """
    per_repeat = []
    pooled = {"active": [], "queue": [], "end_to_end": []}
    aggregate_only = {"active": False, "queue": False, "end_to_end": False}
    for row in rows:
        durations = row.get("durations") or {}
        active = (durations.get("active") or {}).get("p50")
        if active is not None:
            per_repeat.append(active)
        for key in pooled:
            values, from_aggregates = sample_values(row, key)
            pooled[key].extend(values)
            aggregate_only[key] = aggregate_only[key] or from_aggregates
    slot_values = [
        (row.get("pressure") or {}).get("occupied_slot_seconds", {}).get("value")
        for row in rows]
    slot_values = [value for value in slot_values if value is not None]
    summary = {
        "repeats": len(rows),
        "cv_active": coefficient_of_variation(per_repeat),
        "slot_seconds": (round(sum(slot_values), 6) if slot_values else None),
        "evidence": rows[0].get("evidence")
        or (rows[0].get("quality") or {}).get("evidence"),
        "digest": rows[0].get("digest"),
    }
    for key in pooled:
        block = duration_stats(pooled[key], key)
        recorded = ((rows[0].get("durations") or {}).get(key) or {})
        block["evidence"] = recorded.get("evidence", "measured")
        if aggregate_only[key] and pooled[key]:
            block["evidence"] = "derived"
            block["aggregated_from"] = "record_aggregates"
        summary[key] = block
    return summary


#: the largest sample list kept inside a record; beyond it the aggregates stand
#: alone and the artifact stays bounded (#1387: keep artifacts bounded)
SAMPLES_INLINE_LIMIT = 512


def sample_values(row, key):
    """``(values, came_from_aggregates)`` for one duration block of one record."""
    block = (row.get("durations") or {}).get(key) or {}
    values = block.get("samples")
    if isinstance(values, list):
        return [float(v) for v in values if v is not None], False
    if not block.get("n"):
        return [], False
    # bounded artifact: the aggregates are all it carries, so pooling them is
    # the honest maximum and is labelled derived by the caller
    fallback = [block.get(name) for name in ("p50", "mean", "min", "max")]
    return [float(v) for v in fallback if v is not None], True


def ratio(candidate, baseline):
    if baseline in (None, 0) or candidate is None:
        return None
    return round(candidate / baseline, 4)


def build_verdict(baseline_label, candidate_label, baseline_rows, candidate_rows,
                  now=None):
    baseline = arm_summary(baseline_rows)
    candidate = arm_summary(candidate_rows)
    metrics = {}
    for key, base_key in (("active_p50", ("active", "p50")),
                          ("active_p95", ("active", "p95")),
                          ("active_p99", ("active", "p99")),
                          ("active_mean", ("active", "mean")),
                          ("queue_p50", ("queue", "p50")),
                          ("end_to_end_p50", ("end_to_end", "p50")),
                          ("slot_seconds", ("slot_seconds",))):
        if len(base_key) == 1:
            before = baseline.get(base_key[0])
            after = candidate.get(base_key[0])
        else:
            before = (baseline.get(base_key[0]) or {}).get(base_key[1])
            after = (candidate.get(base_key[0]) or {}).get(base_key[1])
        metrics[key] = {"baseline": before, "candidate": after,
                        "ratio": ratio(after, before)}
    verdict = {
        "schema": SCHEMA_VERSION,
        "kind": "verdict",
        "baseline": baseline_label,
        "candidate": candidate_label,
        "ts": parse_now(now),
        "workload_digest": baseline["digest"],
        "family": candidate_rows[0].get("family"),
        "scale": candidate_rows[0].get("scale"),
        "repeats": {"baseline": baseline["repeats"],
                    "candidate": candidate["repeats"]},
        "evidence": {"baseline": baseline["evidence"],
                     "candidate": candidate["evidence"]},
        "repeatability": {"cv_active_baseline": baseline["cv_active"],
                          "cv_active_candidate": candidate["cv_active"]},
        "metrics": metrics,
        "coverage": {
            "baseline": missing_coverage(baseline_rows[0], baseline["cv_active"]),
            "candidate": missing_coverage(candidate_rows[0],
                                          candidate["cv_active"])},
        "sample_size": {
            "baseline_active": baseline["active"]["n"],
            "candidate_active": candidate["active"]["n"],
        },
    }
    return verdict


def load_baseline_file(path):
    with open(path, encoding="utf-8") as handle:
        try:
            payload = json.load(handle)
        except ValueError as exc:
            raise SystemExit("--baseline %s: not JSON (%s)" % (path, exc))
    if not isinstance(payload, dict) or not isinstance(
            payload.get("entries"), list):
        raise SystemExit("--baseline %s must be a baseline file with an "
                         "'entries' list (see scripts/task_perf_baseline.json)"
                         % path)
    for number, entry in enumerate(payload["entries"], 1):
        if not isinstance(entry, dict) or not entry.get("family"):
            raise SystemExit("--baseline %s: entry %d is not an entry with a "
                             "family" % (path, number))
        if not isinstance(entry.get("metrics"), dict):
            raise SystemExit("--baseline %s: entry %d carries no reviewed "
                             "metrics" % (path, number))
    return payload


def find_entry(baseline, family, arm, scale):
    wanted = (family, arm, scale)
    for entry in baseline.get("entries", []):
        if (entry.get("family"), entry.get("arm"), entry.get("scale")) == wanted:
            return entry
    return None


def cmd_gate(args):
    """The nonflaky regression gate: warn or block, with every reason spelled out.

    A check can only block when all of these hold, and the output says which one
    failed when it does not:

      * the mode is ``block`` (the shipped default is ``warn`` - no mandatory
        performance gate exists until a human approves one, per #1387);
      * the arm has a reviewed baseline entry whose ``block`` is true and whose
        ``approved_by`` names a person;
      * the arm is complete (every planned repeat delivered), is adequately
        sampled and its repeatability (CV over the repeat medians) is inside the
        floor of the baseline file;
      * the metric is inside the entry's ratio budget.

    Anything else is a warning or a skip, never a red check on a noisy machine.
    """
    records = load_records(args.infile)
    baseline = load_baseline_file(args.baseline)
    groups = {}
    for record in filter_records(records):
        key = (record["family"], record["arm"], record.get("scale"),
               record.get("seed"), record.get("digest"))
        groups.setdefault(key, []).append(record)
    checks = []
    for _, rows in sorted(groups.items(),
                          key=lambda item: (item[0][0], item[0][1],
                                            str(item[0][2]))):
        family = rows[0]["family"]
        entry = find_entry(baseline, family, rows[0]["arm"],
                           rows[0].get("scale"))
        checks.append(judge(rows, entry, args, baseline))
    by_kind = {}
    for check in checks:
        by_kind[check["verdict"]] = by_kind.get(check["verdict"], 0) + 1
    report = {
        "schema": SCHEMA_VERSION,
        "kind": "gate",
        "ts": parse_now(args.now),
        "mode": args.mode,
        "cv_target": args.cv_target,
        "min_samples": args.min_samples,
        "p95_ratio": args.p95_ratio,
        "counts": by_kind,
        "checks": checks,
        "approval_required": ["%s/%s" % (check["family"], check["arm"])
                              for check in checks
                              if check["verdict"] == "block"],
    }
    print(json.dumps(report, indent=2, sort_keys=True))
    if args.out:
        with open(args.out, "w", encoding="utf-8") as handle:
            handle.write(canonical(report) + "\n")
    print("\ngate mode=%s: %d check(s) - %s" % (
        args.mode, len(checks),
        ", ".join("%s=%d" % (key, value) for key, value in sorted(by_kind.items()))
        or "none"), file=sys.stderr)
    if args.mode == "block" and by_kind.get("block"):
        print("BLOCKING: %s - a mandatory performance gate needs an approved "
              "baseline entry; see the docs page for who may approve one."
              % ", ".join(report["approval_required"]), file=sys.stderr)
        return 1
    return 0


def judge(rows, entry, args, baseline):
    """One arm's verdict plus the reason, so a red line is readable without a debug."""
    record = rows[0]
    family = record["family"]
    arm = record["arm"]
    scale = record.get("scale")
    base = {"family": family, "arm": arm, "scale": scale,
            "workload_digest": record.get("digest"), "repeats": len(rows)}
    if entry is None:
        return dict(base, verdict="skip",
                    reason="no baseline entry for this family/arm/scale; a "
                           "benchmark without a reviewed baseline may not gate")
    if entry.get("workload_digest") and record.get("digest") \
            and entry["workload_digest"] != record.get("digest"):
        return dict(base, verdict="skip",
                    reason="the candidate's workload digest %s differs from the "
                           "baseline entry's %s - different workload, no verdict"
                           % (record.get("digest"), entry["workload_digest"]))
    if not entry.get("reviewed"):
        # the entry names what the runbook measures; the THRESHOLDS of a gate
        # need a human signature first, which is #1387's standing decision
        return dict(base, verdict="skip",
                    reason="the baseline entry of this arm carries no reviewed "
                           "thresholds yet (reviewed/approved_by/reviewed_at); "
                           "a benchmark may report before it may gate")
    summary = arm_summary(rows)
    active = summary["active"]
    cv = summary["cv_active"]
    if not active["n"]:
        return dict(base, verdict="skip", reason="no active-time samples")
    stability = stability_of(record, rows, baseline, cv, args)
    if stability["verdict"] != "stable":
        return dict(base, verdict=stability["verdict"],
                    reason=stability["reason"],
                    stability=stability)
    reasons = []
    verdict = "pass"
    p95_budget = entry.get("p95_ratio", args.p95_ratio)
    for metric, block_key, percentile_key in (
            ("active_p95", "active", "p95"),
            ("active_p50", "active", "p50"),
            ("slot_seconds", "slot_seconds", None)):
        before = (entry.get("metrics") or {}).get(metric)
        if before is None:
            continue
        if block_key == "slot_seconds":
            after = summary["slot_seconds"]
        else:
            after = (summary[block_key] or {}).get(percentile_key)
        if after is None:
            reasons.append("%s_unmeasured" % metric)
            verdict = "warn" if verdict == "pass" else verdict
            continue
        growth = ratio(after, before)
        budget = entry.get("ratio", p95_budget)
        flag = "block" if entry.get("block") and args.mode == "block" else "warn"
        if growth is not None and growth > budget:
            reasons.append("%s grew x%.2f over the reviewed %s (budget x%.2f)"
                           % (metric, growth, block_key, budget))
            verdict = flag
        else:
            base["%s_ratio" % metric] = growth
    if record.get("worker_loss") or (record.get("quality") or {}).get("worker_loss"):
        reasons.append("worker_loss_observed")
        verdict = "warn" if verdict == "pass" else verdict
    return dict(base, verdict=verdict,
                reason="; ".join(reasons) if reasons else
                "inside the reviewed budget of x%.2f"
                % entry.get("ratio", p95_budget),
                stability=stability,
                samples=active["n"],
                evidence=active["evidence"],
                coverage=missing_coverage(record, cv))


def stability_of(record, rows, baseline, cv, args):
    """Repeatability gate: an unstable arm may not block, whatever it measured.

    The per-arm CV floor is a baseline-file decision (``max_cv``), because a
    family whose own floor is 12 % cannot be gated at 3 %; the file's own
    ``stability`` block carries the deployment-wide default.
    """
    stable_floor = args.cv_target
    file_floor = (baseline.get("stability") or {}).get("max_cv")
    entry_floor = None
    for entry in baseline.get("entries", []):
        if entry.get("family") == record["family"] and "max_cv" in entry:
            entry_floor = entry["max_cv"]
    floor = entry_floor or file_floor or stable_floor
    planned = record.get("repeats_planned") or 1
    completed = len(rows)
    if completed < planned:
        return {"verdict": "unstable",
                "reason": "repeat %s of %s planned - the arm is incomplete"
                          % (completed, planned),
                "cv": cv, "floor": floor}
    if cv is None:
        return {"verdict": "unstable",
                "reason": "only one repeat median available; repeatability "
                          "cannot be stated, so no verdict",
                "cv": None, "floor": floor}
    if cv > floor:
        return {"verdict": "unstable",
                "reason": "active-time CV %.3f exceeds the repeatability floor "
                          "%.3f; this arm is too noisy to gate on (see the "
                          "repeatability section of the docs page)"
                          % (cv, floor),
                "cv": cv, "floor": floor}
    return {"verdict": "stable", "reason": "CV %.3f inside floor %.3f" % (cv, floor),
            "cv": cv, "floor": floor}


def contract_of(family):
    """What one unit of this family legitimately pays, as declared in the registry.

    A per-unit expectation is a property of the WORKLOAD, not of whoever happens
    to be running the command. The registry carries it - measured from the
    baseline arm of a real run - so a runner which forgets the flag still judges
    the linear half of the N+1, instead of quietly reporting ``detected=none``
    for a per-row cost. A family which declares nothing judges only super-linear
    growth and says so; the CLI still overrides either way.
    """
    return (FAMILIES.get(family) or {}).get("contract") or {}


def cmd_summary(args):
    """One line per workload cell: the verdict a runbook or a CI log reads.

    `report` prints a row per repeat because the repeats are the evidence; this
    prints one row per (family, scale, arm) because that is the unit a human
    decides on. The ratios are against the ``baseline`` arm of the *same*
    workload, which the digest guarantees - a cell with no baseline beside it
    says so instead of comparing against nothing.
    """
    records = load_records(args.infile)
    cells = {}
    ladders = {}
    for record in filter_records(records):
        family, scale, arm, seed = (record["family"], record.get("scale"),
                                    record["arm"], record.get("seed"))
        # a cell is one arm of one workload - the unit a human decides on; the
        # size ladder that a slope needs spans the cells of one ARM, because the
        # rungs of a ladder are different workloads of the same task
        cells.setdefault((family, scale, arm, seed,
                          record.get("digest")), []).append(record)
        ladders.setdefault((family, arm, seed), []).append(record)
    detections = {}
    for key, rows in ladders.items():
        family, arm, seed = key
        contract = contract_of(family)
        findings = detect_regression(
            rows, budget_seconds=args.slow_body_seconds,
            expected_http_per_unit=(
                args.expected_http_per_unit
                if args.expected_http_per_unit is not None
                else contract.get("http_calls_per_unit")),
            expected_statements_per_unit=(
                args.expected_statements_per_unit
                if args.expected_statements_per_unit is not None
                else contract.get("statements_per_unit")),
            # the same workload's own clean arm: a duplicate which duplicates at
            # every size is linear and invisible to a slope, but not against the
            # baseline it should match
            baseline=ladders.get((family, BASELINE_ARM, seed)))
        detections[key] = [finding["kind"] for finding in findings
                           if finding.get("detected")]
    by_workload = {}
    for (family, scale, arm, seed, digest), rows in cells.items():
        by_workload.setdefault((family, scale, digest, seed), {})[arm] = rows
    lines = []
    for (family, scale, _digest, seed), arms in sorted(
            by_workload.items(),
            key=lambda item: (item[0][0], str(item[0][1]))):
        base_rows = arms.get("baseline")
        for arm, rows in sorted(arms.items()):
            summary = arm_summary(rows)
            active = summary["active"]
            ratio_text = "against no baseline arm"
            if base_rows and arm != "baseline":
                base = arm_summary(base_rows)
                growth = ratio(active["p50"], base["active"]["p50"])
                if growth is not None:
                    ratio_text = "x%s over baseline" % growth
            detected = detections.get((family, arm, seed), [])
            lines.append("%-28s %-10s %-22s n=%-5s p50=%-9s cv=%-7s %s%s" % (
                family, scale or "-", arm, active["n"],
                "-" if active["p50"] is None else round(active["p50"], 4),
                "-" if summary["cv_active"] is None
                else round(summary["cv_active"], 3),
                ratio_text,
                "  DETECTED: %s" % ", ".join(detected) if detected else ""))
    if not lines:
        raise SystemExit("%s holds no workload record to summarize"
                         % args.infile)
    print(chr(10).join(lines))
    if args.out:
        with open(args.out, "w", encoding="utf-8") as handle:
            handle.write("\n".join(lines) + "\n")
    flagged = [line for line in lines if "DETECTED:" in line]
    print("summary: %d cell(s), %d with a detection%s"
          % (len(lines), len(flagged),
             "" if not flagged else " (a report, not a verdict)"),
          file=sys.stderr)
    if args.fail_on and flagged:
        return 1
    return 0


