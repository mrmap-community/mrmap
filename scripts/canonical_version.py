#!/usr/bin/env python3
"""canonical_version: the single canonical application version and its projections.

Run from the repository root as `python3 scripts/canonical_version.py [--write
| --check | --print]`. Standard library only, no docker, no network, no git.
Exit 0 = ok, 1 = the version is missing/invalid or a projection drifted, 2 =
the tool itself could not run.

Why a root VERSION file
----------------------
Issue #1578 measured that the application version was one handwritten Python
constant (`backend/MrMap/__init__.py`) with four readers (OpenAPI document,
system status view, schema cache key, Sphinx) and that every other apparent
source - frontend, docs, changelog - either read that constant or carried no
version at all. #1579 turned the constant into a derived projection: the file
``VERSION`` at the repository root is the only place a human writes the
version, and every consumer reads a projection of it (#1579).

The format is SemVer 2.0.0 exactly as the specification defines it, so a
prerelease (`0.2.0-rc.1`) and an exact build revision as build metadata
(`0.2.0-rc.1+9f8e7d6`) are expressible; anything else is refused. A missing
or invalid file is an error, never a fallback: a deployment that cannot name
its version must not start a silently version-less build.

The projections
---------------
* ``backend/MrMap/version.py`` - a generated one-line module the backend
  package imports, so ``MrMap.VERSION`` and ``MrMap.__version__`` keep
  answering (settings, the OpenAPI document, the system view, the schema
  cache key and Sphinx all import it). It is committed because the backend
  image ships no application code at all: every backend container receives
  ``backend/`` as a bind mount of the checkout, so a version that must reach
  the runtime has to live inside ``backend/``. The generator, not a hand,
  writes it; ``--check`` (and ``scripts/test_canonical_version.py`` in CI)
  fails on drift.
* The frontend needs no committed projection: ``frontend/vite.config.mjs``
  reads this file at build time - the repository root on a checkout,
  ``/VERSION`` in the nginx compile image (``COPY ./VERSION /VERSION``),
  ``/opt/mrmap/VERSION`` in the ``frontend-tests`` container (bind in
  ``docker-compose.dev.yml``) - and fails the build when it is missing or
  invalid. Sphinx reads it through ``MrMap``, which reads the projection.

Usage
-----
  python3 scripts/canonical_version.py --print   # the canonical version
  python3 scripts/canonical_version.py --write   # regenerate projections
  python3 scripts/canonical_version.py --check   # CI drift gate (default)

After editing ``VERSION`` run ``--write`` and commit both files together;
``--check`` is what tells you that you forgot.
"""

import argparse
import re
import sys
from pathlib import Path

# SemVer 2.0.0, the grammar exactly as https://semver.org specifies it: major
# . minor . patch, each without leading zeros, an optional prerelease and an
# optional build metadata ("+" revision) section.
SEMVER_PATTERN = re.compile(
    r'^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)'
    r'(?:-(?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*'
    r'(?:\.(?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*))*))?'
    r'(?:\+(?:[0-9a-zA-Z-]+(?:\.[0-9a-zA-Z-]+)*))?$'
)

VERSION_FILE = 'VERSION'
PROJECTION = 'backend/MrMap/version.py'

PROJECTION_TEMPLATE = '''"""The application version - a generated projection of the root VERSION file.

Generated by `python3 scripts/canonical_version.py --write` (#1579); do not
edit. The canonical value lives in the file `VERSION` at the repository root
(one line, strict SemVer). This file is committed because the backend image
carries no application code and every backend container receives `backend/`
as a bind mount: the version must travel inside `backend/` to reach the
runtime without git or a working directory. Drift against `VERSION` is a CI
failure; the fix is to edit `VERSION` and re-run the generator, never to
edit this file.

The version line carries the marker `x-release-please-version` (#1581): the
release planner of epic #1577 rewrites `VERSION` and this projection together
in its pull request, so the projection cannot drift on a release branch. The
marker is a comment; the generator writes it, `--check` regenerates the whole
file including the marker, and `--check` therefore also fails on a projection
whose version moved without `VERSION` moving with it.
"""

VERSION = '{version}'  # x-release-please-version
'''


class VersionError(Exception):
    """The canonical version is missing, malformed, or a projection drifted."""


def read_version(root):
    """Return the canonical version string of the checkout rooted at root.

    Strips surrounding whitespace (the file ends with a newline) and refuses
    anything the SemVer grammar does not accept, naming what it read. Raises
    VersionError when the file is absent - there is no fallback version.
    """
    path = Path(root) / VERSION_FILE
    try:
        raw = path.read_text(encoding='utf-8')
    except FileNotFoundError:
        raise VersionError(
            f'{VERSION_FILE} is missing at the repository root {root}. The '
            'canonical application version is a file, not a guess; nothing '
            'here can proceed without it.') from None
    version = raw.strip()
    if not SEMVER_PATTERN.match(version):
        raise VersionError(
            f'{VERSION_FILE} must hold one strict SemVer 2.0.0 version '
            f'(major.minor.patch, optional -prerelease, optional +buildmeta); '
            f'{root}/{VERSION_FILE} reads {raw!r}.')
    return version


def projection_path(root):
    return Path(root) / PROJECTION


def render_projection(version):
    return PROJECTION_TEMPLATE.format(version=version)


def write_projection(root, version):
    """Write the backend projection of version; return its path."""
    path = projection_path(root)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_projection(version), encoding='utf-8')
    return path


def check(root):
    """Return a list of drift messages - empty means the checkout is coherent.

    Checks the canonical file itself (present, valid, single logical line) and
    that the committed backend projection carries exactly that version.
    """
    problems = []
    try:
        version = read_version(root)
    except VersionError as error:
        return [str(error)]
    raw = (Path(root) / VERSION_FILE).read_text(encoding='utf-8')
    if len([line for line in raw.splitlines() if line.strip()]) != 1:
        problems.append(f'{VERSION_FILE} must hold exactly one line.')
    path = projection_path(root)
    if not path.exists():
        problems.append(
            f'{PROJECTION} is missing; run '
            '`python3 scripts/canonical_version.py --write`.')
        return problems
    if path.read_text(encoding='utf-8') != render_projection(version):
        problems.append(
            f'{PROJECTION} does not match {VERSION_FILE} ({version}); run '
            '`python3 scripts/canonical_version.py --write` and commit both.')
    return problems


def main(argv=None):
    parser = argparse.ArgumentParser(
        description=__doc__.splitlines()[0], allow_abbrev=False)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--print', action='store_true', dest='print_version',
                      help='print the canonical version and exit')
    mode.add_argument('--write', action='store_true',
                      help='(re)generate the committed projections')
    mode.add_argument('--check', action='store_true',
                      help='verify canonical file and projections (default)')
    parser.add_argument('--root', default='.',
                        help='repository root (default: the current directory)')
    args = parser.parse_args(argv)

    if args.print_version:
        try:
            print(read_version(args.root))
        except VersionError as error:
            print(f'canonical_version: {error}', file=sys.stderr)
            return 1
        return 0

    try:
        version = read_version(args.root)
    except VersionError as error:
        print(f'canonical_version: {error}', file=sys.stderr)
        return 1

    if args.write:
        path = write_projection(args.root, version)
        print(f'canonical_version: wrote {path} with {version}')
        return 0

    problems = check(args.root)
    for problem in problems:
        print(f'canonical_version: {problem}', file=sys.stderr)
    if problems:
        return 1
    print(f'canonical_version: {version}, projections in sync')
    return 0


if __name__ == '__main__':
    sys.exit(main())
