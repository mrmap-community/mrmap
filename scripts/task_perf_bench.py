#!/usr/bin/env python3
"""task_perf_bench - runtime benchmark and regression report for Celery task families.

Host-side benchmark tool carried by this repository (issue #1396, epic #1387); run it
as `python3 scripts/task_perf_bench.py ...` from the repository root. Like
`scripts/http_process_bench.py` (the web tier's half of the same reading) and
`scripts/stack_memory_profile` (the RAM half), it is a tool of the checkout and not
part of the deployed application, and it is stdlib only: it runs wherever `python3`
runs, on the runner or on an operator's laptop.

What it owns is the READING and the VERDICT. The workload itself is generated by the
Django suite, because the fixtures, the models and the mocked remote endpoints of the
application are the only reproducible description of "a harvest chunk", "a probe run"
or "an update apply" there is:

    python3 manage.py test tests.django.system.test_task_runtime_bench \
        --noinput --keepdb

    python3 scripts/task_perf_bench.py load --family harvesting.import_chunk \
        --arm baseline --repeats 7 --seed 20261121 --out task-perf.jsonl

    python3 scripts/task_perf_bench.py report --in task-perf.jsonl
    python3 scripts/task_perf_bench.py compare --in task-perf.jsonl \
        --baseline baseline --candidate sql-n-plus-one
    python3 scripts/task_perf_bench.py gate --in task-perf.jsonl \
        --baseline scripts/task_perf_baseline.json --mode warn --out verdict.json

The three durations the epic insists on keeping apart (#1330, and #1395's V1 promise
that a duration is never smuggled into a statement count) are three columns here and
never a sum:

    active              what a worker really occupied, per attempt
                        (``CeleryTaskAttempt.active_seconds`` of #1330; the workload
                        runner also records its own monotonic per-iteration time for
                        the units which do not run inside a worker at all)
    queue               ``started_at - published_at`` of the same rows - broker wait,
                        reported separately, never added to the active time
    end_to_end          whole-workflow elapsed of the run behind the attempts,
                        reported separately again

Every number carries its evidence quality (``measured`` / ``derived`` /
``projected``) and its sample size, and an unmeasured thing stays ``null`` instead of
becoming a zero: a p99 over four attempts is printed as ``p99(4)`` or not at all,
which is the acceptance criterion "never invent samples" in code.

Determinism is a hard requirement, because a benchmark nobody can repeat cannot
regress anybody: every record names its seed and its workload digest (the sha256 of
the canonicalized workload spec), and `compare` REFUSES arms whose workload digest
differs. A comparison of two different workloads is not a regression report.

Safety promise, same scope rule as the sibling tools: it only reads the JSONL it is
given and the files it is told to, writes only `--out`, starts no container, sends
nothing to the network and reads no credential. The heavy fixtures it describes are
deterministic synthetic rows - no private production endpoint is involved, and no
command of this tool talks to a deployment at all.

Usage:
  python3 scripts/task_perf_bench.py load   --family NAME --arm LABEL [--out FILE]
                      [--repeats N] [--seed N] [--scale NAME]
                      [--fixture PATH] [--fixture-dir DIR]
                      [--notes TEXT] [--revision SHA] [--now ISO]
                      [--concurrency N] [--worker-count N] [--queue NAME]
                      [--postgis VER] [--pg VER] [--cpu NAME] [--cores N]
                      [--memory-limit BYTES] [--cgroup-limit BYTES]
                      [--cache STATE] [--mock STATE] [--tasks CSV] [--units CSV]
                      [--sql-ms MS] [--sql-count N] [--http-calls N]
                      [--outliers JSON]
                      [--retry N] [--failure N] [--error N] [--revoked N]
                      [--abandoned N] [--open N] [--retained-truncated]
                      [--worker-loss N] [--evidence KIND]
  python3 scripts/task_perf_bench.py record --in RECORD.json --out FILE
  python3 scripts/task_perf_bench.py report --in FILE [--family NAME] [--arm LABEL]
                      [--scale NAME]
  python3 scripts/task_perf_bench.py compare --in FILE --baseline LABEL
                      --candidate LABEL [--family NAME] [--scale NAME]
                      [--now ISO] [--out FILE]
  python3 scripts/task_perf_bench.py gate   --in FILE --baseline FILE
                      [--mode warn|block] [--out FILE]
  python3 scripts/task_perf_bench.py summary --in FILE [--out FILE] [--fail-on]
  python3 scripts/task_perf_bench.py detect --in FILE --arm LABEL [--family NAME]
                      [--slow-body-seconds S] [--expected-http-per-unit N]
                      [--expected-statements-per-unit N] [--fail-on] [--out FILE]

`load --fixture` reads the JSON a benchmark run wrote next to its timings; the shape
is documented in docs/source/development/celery-task-runtime-benchmarks.rst and the
offline suite writes one with its own numbers, so the reader of either can trust the
keys without guessing them.
"""

