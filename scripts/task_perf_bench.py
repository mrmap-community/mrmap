def add_common(parser):
    # reserved for future global flags; keeps the subcommands identical in shape
    parser.add_argument("--version", action="store_true",
                        help="print the schema version and exit")


def main(argv=None):
    args = build_parser().parse_args(argv)
    if getattr(args, "version", False):
        print(SCHEMA_VERSION)
        return 0
    if args.command == "load":
        return cmd_load(args)
    if args.command == "record":
        return cmd_record(args)
    if args.command == "report":
        return cmd_report(args)
    if args.command == "compare":
        return cmd_compare(args)
    if args.command == "gate":
        return cmd_gate(args)
    if args.command == "summary":
        return cmd_summary(args)
    if args.command == "detect":
        return cmd_detect(args)
    if args.command == "families":
        return cmd_families(args)
    return 1


def apply_numeric_overrides(record, args):
    """The aggregate knobs of the CLI, merged into a record's pressure/sql/http blocks.

    Separate from `build_record` so the offline suite can call it directly and a
    reader can see exactly which CLI flag lands in which field.
    """
    if args.sql_ms is not None:
        record.setdefault("sql", {})["total_ms"] = {
            "value": args.sql_ms, "evidence": "measured"}
    if args.sql_count is not None:
        record.setdefault("sql", {})["statements"] = {
            "value": args.sql_count, "evidence": "measured"}
    if args.http_calls is not None:
        record.setdefault("http", {})["calls"] = {
            "value": args.http_calls, "evidence": "measured"}
    if args.outliers:
        try:
            outliers = json.loads(args.outliers)
        except ValueError as exc:
            raise SystemExit("--outliers is not JSON (%s)" % exc)
        if not isinstance(outliers, dict):
            raise SystemExit("--outliers must be a JSON object")
        record.setdefault("pressure", {})["outliers"] = outliers
    for name, value in (("retry", args.retry), ("failure", args.failure),
                        ("error", args.error), ("revoked", args.revoked)):
        if value is not None:
            record.setdefault("outcomes", {})[name] = {
                "count": value, "evidence": "measured"}
    if args.open_ is not None:
        record.setdefault("outcomes", {})["open"] = {
            "count": args.open_, "evidence": "measured"}
    for name, value in (("abandoned", args.abandoned),
                        ("worker_loss", args.worker_loss)):
        if value is not None:
            record.setdefault("uncertain", {})[name] = {
                "count": value, "evidence": "measured"}
    if args.retained_truncated:
        quality = record.setdefault("quality", {})
        quality["retention_truncated"] = True
        quality.setdefault("retention_note",
                           "window truncated by the retention sweep of #1330")
    return record


if __name__ == "__main__":
    sys.exit(main())
