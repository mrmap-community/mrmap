# ------------------------------------------------------------------- discovery


def discover_fixture_files(args):
    """Every candidate workload JSON the invocation names, in a stable order.

    A single `--fixture`, a `--fixture-dir` swept for ``*.json``, or both. Sorted
    by path so the same directory always produces the same arm order.
    """
    paths = []
    if getattr(args, "fixture", ""):
        paths.append(args.fixture)
    directory = getattr(args, "fixture_dir", "")
    if directory:
        if not os.path.isdir(directory):
            raise SystemExit("--fixture-dir %s is not a directory" % directory)
        for name in sorted(os.listdir(directory)):
            if name.endswith(".json"):
                paths.append(os.path.join(directory, name))
    if not paths:
        raise SystemExit("load wants --fixture PATH or --fixture-dir DIR "
                         "(the JSON a benchmark run wrote next to its timings)")
    for path in paths:
        if not os.path.isfile(path):
            raise SystemExit("--fixture %s is not a file" % path)
    return paths


def read_fixture(path):
    with open(path, encoding="utf-8") as handle:
        try:
            payload = json.load(handle)
        except ValueError as exc:
            raise SystemExit("%s: not JSON (%s)" % (path, exc))
    if not isinstance(payload, dict):
        raise SystemExit("%s: a workload fixture is one object" % path)
    return payload


#: which keys may arrive from a fixture file; a key named on the command line
#: wins, so a runbook can override one field without editing the JSON. The
#: identity keys (arm, repeat, seed, ...) belong to the file a benchmark run
#: wrote - a directory of them loads without repeating what each already says.
FIXTURE_WORKLOAD_KEYS = ("family", "fixture", "scale", "records", "chunks",
                         "chunk_size", "attempts_per_unit", "queue",
                         "queue_config", "mock_responses", "tasks",
                         "arm", "repeat", "repeats_planned", "repeats_mode",
                         "seed", "ts", "revision", "notes")


def build_record(args, fixture=None):
    """Merge fixture, CLI and environment into one record, then validate it.

    The precedence is deliberate: defaults < environment probe < fixture < CLI.
    A measured number therefore always beats a probed one, and a human on the
    command line always beats both.
    """
    record = {
        "schema": SCHEMA_VERSION,
        "kind": "load",
        "arm": args.arm,
        "repeat": args.repeat,
        "repeats_planned": args.repeats_planned,
        "repeats_mode": args.repeats_mode,
        "seed": args.seed,
        "ts": parse_now(args.now),
        "notes": args.notes,
        "revision": args.revision or detect_revision(),
        "environment": probe_environment(args),
        "durations": {},
        "outcomes": {},
        "uncertain": {},
        "pressure": {},
        "quality": {},
    }
    if fixture:
        for key in FIXTURE_WORKLOAD_KEYS:
            if fixture.get(key) is not None:
                record[key] = fixture[key]
        for key in ("durations", "outcomes", "uncertain", "pressure",
                    "quality", "sql", "http", "workload", "resource",
                    "instrumentation", "coverage"):
            if isinstance(fixture.get(key), dict):
                record[key] = dict(fixture[key])
        if isinstance(fixture.get("environment"), dict):
            # verbatim, and not merged over this host's probe: the environment of
            # a record is the one the RUN measured. A merge would let the machine
            # that happens to run `load` into the identity of a workload, and an
            # analyst re-loading an artifact on another host would then get a
            # different digest for the same measurement - which `compare` would
            # refuse as "different workloads". The probe stays the fallback for a
            # fixture which does not describe its environment, and the CLI still
            # overrides both.
            record["environment"] = dict(fixture["environment"])
        if fixture.get("evidence"):
            record["evidence"] = fixture["evidence"]
        if fixture.get("units"):
            record["units"] = list(fixture["units"])
        if fixture.get("correlation"):
            record["correlation"] = fixture["correlation"]
    apply_cli_overrides(record, args)
    apply_numeric_overrides(record, args)
    finalize_record(record)
    validate_record(record, source="load")
    return record


def apply_cli_overrides(record, args):
    """The CLI's own knobs, applied over whatever a fixture carried."""
    for key, value in (("family", args.family), ("scale", args.scale),
                       ("fixture", args.fixture_kind)):
        if value:
            record[key] = value
    if args.tasks:
        record["tasks"] = [name.strip() for name in args.tasks.split(",")
                           if name.strip()]
    if args.concurrency is not None:
        record["concurrency"] = args.concurrency
    if args.worker_count is not None:
        record["worker_count"] = args.worker_count
    if args.queue:
        record["queue"] = args.queue
    if args.queue_config:
        record["queue_config"] = args.queue_config
    if args.cache:
        record.setdefault("environment", {})["cache"] = args.cache
    if args.mock:
        record["mock_responses"] = args.mock
    if args.units:
        record["units"] = [name.strip() for name in args.units.split(",")
                           if name.strip()]
    if args.evidence:
        record["evidence"] = args.evidence
    if args.revision:
        record["revision"] = args.revision
    environment = record.setdefault("environment", {})
    for key, value in (("postgis", args.postgis), ("postgres", args.pg),
                       ("cpu", args.cpu), ("cores", args.cores),
                       ("memory_limit_bytes", args.memory_limit),
                       ("cgroup_limit_bytes", args.cgroup_limit)):
        if value is not None and value != "":
            environment[key] = value
    if args.notes:
        record["notes"] = args.notes


def _is_runner_clock_attempt(attempt):
    """Whether one attempt row is the workload runner's own stopwatch, not #1330.

    The bench suite has to time a unit whose body never reaches a worker (a direct
    ``.run()`` fires no Celery signals), and when the collector saw nothing it
    writes a row in the SHAPE of an attempt row - same ``active_seconds`` field, a
    synthesised ``task_id``, and a ``quality`` list naming what it is. The analyzer
    must not read that shape as the #1330 claim it imitates: "measured" means
    "observed from worker signals of an actual execution", which is the distinction
    #1330 exists to keep and the one acceptance bullet 2 of #1396 is graded on.
    """
    quality = attempt.get("quality")
    if isinstance(quality, str):
        quality = [quality]
    if isinstance(quality, list) and any(
            str(item).startswith("no_collector_row") for item in quality):
        return True
    return str(attempt.get("task_id") or "").startswith("runner-")


def _active_evidence(record, attempts):
    """The evidence label of the active sample, read from where it came from.

    Never promoted: one runner-clock row in the sample and the whole block is
    labelled as the runner's clock, because a block which contains a stopwatch
    reading cannot claim to be worker-signal-measured. ``samples`` on the block
    says how many were runner rows, so a mixed sample stays visible instead of
    quietly deciding in favour of the better label.
    """
    if not attempts:
        return "measured", 0
    runner_rows = sum(1 for attempt in attempts if _is_runner_clock_attempt(attempt))
    if runner_rows:
        return "measured_local", runner_rows
    if (record.get("quality") or {}).get("evidence") == "measured_local" or \
            record.get("evidence") == "measured_local":
        return "measured_local", 0
    return "measured", 0


def finalize_record(record):
    """Derive what a caller did not hand in, and label every derivation."""
    workload = record.setdefault("workload", {})
    units = record.get("units")
    durations = record.setdefault("durations", {})
    if units:
        workload.setdefault("units", len(units))
    attempts = sum(len(unit.get("attempts", [])) for unit in (units or []))
    workload.setdefault("attempts", attempts)
    # active time: from the unit attempts when they exist
    active_attempts = [attempt for unit in (units or [])
                       for attempt in unit.get("attempts", [])]
    active = [attempt.get("active_seconds") for attempt in active_attempts
              if attempt.get("active_seconds") is not None]
    waits = [attempt.get("wait_seconds") for unit in (units or [])
             for attempt in unit.get("attempts", [])
             if attempt.get("wait_seconds") is not None]
    if active:
        durations["active"] = duration_stats(active, "active")
        # labelled from where the numbers came from, never asserted: see
        # `_active_evidence`. A runner stopwatch is a legitimate measurement of
        # the workload's own duration and a wrong claim about worker-occupied
        # time, and the reader has to be able to tell the two apart.
        evidence, runner_rows = _active_evidence(record, active_attempts)
        durations["active"]["evidence"] = evidence
        if durations["active"]["p95"] is not None:
            durations["active"]["p95_evidence"] = evidence
        if runner_rows:
            durations["active"]["runner_clock_samples"] = runner_rows
        # the raw samples ride along up to a bound, so pooling across repeats is
        # a percentile over attempts and not an aggregate of aggregates
        durations["active"]["samples"] = active[:SAMPLES_INLINE_LIMIT]
        durations["active"]["samples_bounded"] = len(active) > SAMPLES_INLINE_LIMIT
    if waits:
        durations["queue"] = duration_stats(waits, "queue")
        durations["queue"]["evidence"] = "measured"
        durations["queue"]["samples"] = waits[:SAMPLES_INLINE_LIMIT]
        durations["queue"]["samples_bounded"] = len(waits) > SAMPLES_INLINE_LIMIT
    # fixed-workload totals: derived from the measured samples, never re-measured
    terminal_active = [attempt.get("active_seconds") for unit in (units or [])
                       for attempt in unit.get("attempts", [])
                       if attempt.get("active_seconds") is not None
                       and attempt.get("outcome", "")]
    if terminal_active:
        record["pressure"]["occupied_slot_seconds"] = {
            "value": round(sum(terminal_active), 6),
            "samples": len(terminal_active),
            "evidence": "derived",
        }
    outcomes = record.setdefault("outcomes", {})
    counted = {}
    for unit in (units or []):
        for attempt in unit.get("attempts", []):
            name = attempt.get("outcome") or "open"
            counted[name] = counted.get(name, 0) + 1
    for name, value in counted.items():
        outcomes.setdefault(name, {"count": value, "evidence": "measured"})
    # queue wait is reported as its own block, never folded into active
    if durations.get("queue") and "queue" not in outcomes:
        outcomes.setdefault("stamped", {
            "count": durations["queue"]["n"], "evidence": "measured"})
    record["quality"].setdefault("evidence", record.get("evidence", "measured"))
    record["quality"].setdefault("labels", sorted(EVIDENCE_LABELS))
    if record.get("evidence") not in EVIDENCE_LABELS:
        record.setdefault("quality", {})["unknown_evidence"] = record.get("evidence")
    # end-to-end is its own number, and unknown stays unknown
    elapsed = [unit.get("elapsed_seconds") for unit in (units or [])
               if unit.get("elapsed_seconds") is not None]
    if elapsed:
        durations["end_to_end"] = duration_stats(elapsed, "end_to_end")
        durations["end_to_end"]["evidence"] = record.get(
            "evidence", "measured")
        durations["end_to_end"]["samples"] = elapsed[:SAMPLES_INLINE_LIMIT]
        durations["end_to_end"]["samples_bounded"] = (
            len(elapsed) > SAMPLES_INLINE_LIMIT)
    record["digest"] = workload_digest(record)


def detect_revision():
    """The commit of this checkout, when git answers; never required.

    A benchmark without its code revision is not reproducible, so the field is
    validated as mandatory - but the tool must run from an exported tree too, and
    then it says None rather than lying.
    """
    try:
        import subprocess  # nosec B404 - read-only git call, no shell
        out = subprocess.run(  # nosec B603 - fixed argv, no shell
            ["git", "rev-parse", "HEAD"],
            cwd=os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
            capture_output=True, text=True, timeout=10)
    except Exception:
        return None
    if out.returncode != 0:
        return None
    return out.stdout.strip() or None


def probe_environment(args):
    """What the host answers about itself - cheap, and null when it does not answer.

    The acceptance criterion is that the environment is *documented*, so every
    field is a reading with a source, and a missing reading stays None instead
    of a plausible constant.
    """
    environment = {
        "platform": platform.platform(),
        "python": platform.python_version(),
        "hostname": socket.gethostname(),
        "machine": platform.machine(),
        "cores": os.cpu_count(),
        "cpu": None,
        "postgis": None,
        "postgres": None,
        "memory_bytes": None,
        "memory_limit_bytes": None,
        "cgroup_limit_bytes": None,
        "cache": None,
        "clock": "monotonic",
    }
    try:
        pages = os.sysconf("SC_PHYS_PAGES")
        page_size = os.sysconf("SC_PAGE_SIZE")
        if pages and page_size:
            environment["memory_bytes"] = int(pages) * int(page_size)
    except (ValueError, OSError, AttributeError):
        pass
    limit = read_first_cgroup_limit()
    environment["cgroup_limit_bytes"] = limit
    if limit:
        environment["memory_limit_bytes"] = limit
    model = cpu_model()
    environment["cpu"] = model if model else None
    return environment


def read_first_cgroup_limit():
    """The memory limit of the *current* cgroup, v2 then v1.

    #1054's rule: a measurement taken inside a container is a measurement of
    that cgroup, not of the machine, so the limit has to be on the record.
    """
    candidates = ("/sys/fs/cgroup/memory.max",
                  "/sys/fs/cgroup/memory/memory.limit_in_bytes")
    for path in candidates:
        try:
            with open(path, encoding="utf-8") as handle:
                text = handle.read().strip()
        except OSError:
            continue
        if text in ("", "max"):
            continue
        try:
            value = int(text)
        except ValueError:
            continue
        # v1 reports "no limit" as a huge number, not as the string max
        if value >= 2 ** 62:
            continue
        return value
    return None


def cpu_model():
    try:
        with open("/proc/cpuinfo", encoding="utf-8") as handle:
            for line in handle:
                if line.lower().startswith("model name"):
                    return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return None


